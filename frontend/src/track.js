/**
 * 埋点 —— 阶段 9.6b 的**前置**，当前是占位实现。
 *
 * ## ★★★ 为什么先写这个文件，哪怕它现在什么都不做
 *
 * 阶段 9.6b 要做「在线指标」，而在线指标的第一个问题是
 * **「点上有没有事件可埋」**。在 9.6b 之前，引用卡片是一个纯粹的
 * `<span>` 序列 —— 没有 `<a>`、没有 `@click`、没有 hover 态。
 * 也就是说：**我们不是「还没接埋点」，是根本没有可埋的时刻。**
 *
 * 所以这一步先补的是**行为**，不是上报。
 *
 * ## ★ 它现在是「真的打了，只是打在控制台上」
 *
 * 这个函数**不空转** —— 每次调用都会 `console.info` 一条结构化的事件。
 * 理由：一份「写了但没人验证过会跑」的埋点，和没写没有区别
 * （同 `eval_report.py` 那条：「一份只被写过、没被跑过的检查，
 * 在验收上和没写过一样」，见 `docs/10` 坑 51 附近）。
 * 打了控制台，这个前置就**当场可验**：打开 F12 点一下引用，
 * 看得见 `[track] ref_click {...}` 才算过。
 *
 * ## ★★ 等 9.6b 建成之后，只有这一个文件要改
 *
 * ```
 *   建 V18（user_event 表）+ 上报端点
 *     → 把下面的 console.info 换成 navigator.sendBeacon(...)
 *     → 其余一行不动
 * ```
 *
 * ★ 这就是把埋点收口成一个函数的意义：**如果每个组件各写一次上报，
 * 「换了上报方式」就变成一次全局搜索** —— 而漏掉一处的症状是
 * 「那个事件永远收不到」，没有任何报错。
 *
 * ## ★ 为什么用 sendBeacon（现在先记在这里，实现时照着做）
 *
 * 用户点完引用可能**立刻关页面 / 跳转**。`fetch` 在 unload 时会被浏览器
 * 取消，那一条事件就静静地没了 —— 而它是**唯一**能说明「用户真的去看了」
 * 的证据。`sendBeacon` 是浏览器专门为此提供的：它把请求交给浏览器，
 * 页面关掉也照样发出去。
 *
 * @param {string} type 事件类型。当前两个：`ref_click` / `feedback`
 * @param {object} payload 事件载荷。★ **不要塞正文** —— 埋点表存的是行为，
 *        不是内容；塞进去会让这张表变成第二份对话记录
 */
export function track(type, payload = {}) {
  // ★ 时间戳在【客户端】取，不是服务端。理由是「用户什么时候点的」
  //   和「服务端什么时候收到的」在网络抖动时会差开，
  //   而「点击 → 下单」这类时间窗口径要的是前者。
  //   ⚠️ 代价：客户端时钟可以不准（甚至能被改）。所以 9.6b 建表时
  //   `occurred_at`（客户端报的）和 `received_at`（服务端写的）
  //   **要分成两列**，不能只留一个 —— 只留一个的话，
  //   「时钟偏了」和「网络慢了」在数据上长得一模一样。
  const event = { type, ...payload, occurredAt: new Date().toISOString() }

  console.info('[track]', type, event)

  return event
}
