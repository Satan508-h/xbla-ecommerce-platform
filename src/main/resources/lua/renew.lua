--[[
  续期 —— 阶段 6.9 补上的第四个脚本。看门狗的一次心跳。

  ============================================================
  ★★★ 它的全部意义：**续期【不能创建】名额**
  ============================================================

  在这之前，续期是 Java 侧的两条普通命令：

      ZADD slots <新过期时间> <traceId>
      ZADD alive <now>        <traceId>

  问题出在 ZADD 的语义上：**成员不存在时它会把它【创建】出来。**

  而「续期」这件事的前提是「我【还】持有这个名额」（re-new = 再次变新）。
  一个已经不存在的名额，没有任何理由被「再次变新」—— 它只应该保持不存在。

  于是有了这个窗口（真机上抓到过，12 轮压测复现 1 次）：

      t0  心跳：heldSnapshot() → 快照里有 X
      t1  release(X)：registry.forget(X)          ← 本机忘了
      t2  release(X)：ZREM slots X                ← Redis 也删了
      t3  心跳：ZADD slots X (now + ttl)          ← 用【过期快照】把 X 复活

  净结果：slots 里躺着一个 X，TTL 全新，而**本机不认领它**
  （registry 里没有 → 没人续期 → 没人释放）。它要占着名额直到 TTL 到期。

  ★ 这个窗口只有毫秒级，但每次 release 都有一次机会撞上，
    而命中的后果是【容量静默变少】—— 8 个名额可能实际只有 5 个能用，
    没有异常、没有日志、没有任何指标能看出来。
    实测那次：100 并发跑了 23.6 秒而不是 15.9 秒，正好是「有效并发 5 而不是 8」。

  ============================================================
  ★★ 为什么是「判定 + 延长」而不是「只延长」
  ============================================================

  ZSCORE 判定把它从「写着写着创建了」变成「先确认还在，才延长」——
  这是所有租约系统的标准语义：**keepalive 不能创建租约**
  （etcd 的 Lease.KeepAlive、Chubby 的 KeepAlive 都是这个形状）。
  结构上让复活不可能，而不是靠把窗口缩得更小。

  ⚠️ 它改变了一条既有策略，那条策略的注释就在 ChatPermitService 里：
  原文是「续期失败【只记日志、不放弃】—— 抖动是暂时的，主动放弃反而把名额真空出来」。
  现在多了一种情况：**Redis 侧真的已经没有这个名额了**（心跳失败超过 TTL，
  它被回收、甚至已被别人合法抢走）。这时续期返回 0，我们**确实放弃了**。

  ★ 放弃在这里是对的：名额已经不在了，「拉回来」才是真的超卖。
    抖动（连不上）走的是另一条路 —— execute 会抛异常，那条仍然是「只记日志不放弃」。
    两者在 Java 侧用不同的分支处理，见 ChatPermitService.renewHeld。

  ============================================================
  KEYS / ARGV
  ============================================================

    KEYS[1] slots   ZSet  成员=traceId  score=过期毫秒
    KEYS[2] alive   ZSet  成员=traceId  score=最后心跳毫秒

    ARGV[1] traceId
    ARGV[2] nowMs   当前毫秒时间戳（★ 由 Java 传，和 acquire.lua 同一个理由）
    ARGV[3] ttlMs   名额租期

  返回值：1 = 续期成功；0 = 它已经不在名额表里了（调用方该记一条 WARN）

  ★ 两条命令仍然在一个脚本里，虽然它们没有「读-判断-写」的关系 ——
    真正的理由是【它们要一起成功或一起失败】：
    只延长了 slots 而没更新 alive，cleanup 就会把 holder 当死人看
    （它的队列条目会被误清）。原子性是免费的，所以顺手拿上。
--]]

-- ★ 判定：成员【存在】才续期。这一行就是本脚本存在的全部理由。
--   ⚠️ 注意 ZSCORE 对「已过期但还没被扫掉」的成员仍然返回分数 ——
--     那是【对的】：score 过期只说明租期到了，而持有者还在跑，
--     这正是看门狗要救回来的情况。真正不该救的是「成员根本不在了」。
if redis.call('ZSCORE', KEYS[1], ARGV[1]) then
    redis.call('ZADD', KEYS[1], tonumber(ARGV[2]) + tonumber(ARGV[3]), ARGV[1])
    redis.call('ZADD', KEYS[2], ARGV[2], ARGV[1])
    return 1
end

return 0
