--[[
  释放名额 —— 阶段 6.3 的第二个脚本。

  ============================================================
  ★★ 它【不】把名额分给任何人
  ============================================================

  docs/02 §22 原来写的是「释放名额 + 原子地分配给队首」，
  并把它当作「为什么不用 INCR/DECR」的面试答案。

  改成「只移除自己 + 广播」之后，那个答案要换一个 —— 换完其实更好：

    旧：因为要「释放 + 分配」原子，否则名额会空转或被插队。
    新：因为分配必须【只有一个地方能决定】。让释放者去分配，它就得先回答
        「队首还活着吗」—— 而那个答案它拿不到（Redis 里没有「这个连接还在不在」）。
        不回答就会把名额分给幽灵，回答就得再引入一张存活表。
        把分配留给 acquire，死人不参与竞争，「无死锁」就是结构保证而不是兜底。

  ============================================================
  KEYS / ARGV
  ============================================================

    KEYS[1] slots  KEYS[2] queue  KEYS[3] alive
    ARGV[1] traceId
    ARGV[2] channel        Pub/Sub 频道名（频道不是 key，只能走 ARGV）

  返回值：真正释放掉的名额数（0 或 1）。

  ★★ 为什么返回这个数而不是恒返回 1：
     freed == 0 表示「来释放的人并不持有名额」—— 可能是重复释放、
     也可能是它的名额因为续期失败而已经被回收了。这两种情况都值得记一条 WARN，
     因为它们意味着「我以为我在占着名额，其实没有」，而那种状态下我可能正在超卖。
     对应「释放锁时误删了别人的锁」在名额场景下的那个问题。

  ★ 三个 ZREM 都要做，不只做 slots：
    - queue：正常路径下持有者不在队列里，但「拿了名额后客户端断开」那条路
      会先摘队列再释放，顺序不保证，多删一次是幂等的
    - alive：不删的话，它会以「已死但心跳还新」的状态留在 alive 里，
      直到心跳过期才被 cleanup 扫走 —— 白白让 cleanup 多做一次无用功
--]]

-- ★ 先取返回值再删：ZREM 的返回值就是「原本在不在里面」
local freed = redis.call('ZREM', KEYS[1], ARGV[1])
redis.call('ZREM', KEYS[2], ARGV[1])
redis.call('ZREM', KEYS[3], ARGV[1])

-- ★ 只有真的空出了一个位置才广播。
--   排队中的请求主动退出（用户关页面）不空名额，就不该把所有人叫醒一次 ——
--   惊群本身不贵，但没必要的惊群会让「谁被唤醒了几次」这件事没法从日志上看出来。
if freed > 0 then
    -- ⚠️ 脚本里的 PUBLISH，Redis 保证在【脚本执行完之后】才投递，
    --    所以订阅者收到消息时，上面那些 ZREM 的效果已经可见了。
    --    这条保证了「被唤醒的人一定能抢到刚空出来的那个位置」。
    redis.call('PUBLISH', ARGV[2], ARGV[1])
end

return freed
