-- ============================================================
-- 一、为什么需要这两列
-- ============================================================
--
-- CLAUDE.md 说阶段 4 的关键词召回用「PostgreSQL 全文检索」。
-- 但 PostgreSQL 内置的分词器是为英文设计的，中文根本切不开 ——
-- 这是在本项目的库上实测出来的，不是推测：
--
--   SELECT to_tsvector('simple', '电池容量是5000mAh支持快充');
--   →  '电池容量是5000mah支持快充':1        ← 整句粘成一个词元
--
-- 后果是关键词召回几乎全废。实测漏检率（全库 1652 条切片）：
--
--   词      裸 FTS 命中    content LIKE 命中    漏检率
--   退货        3               43              93%
--   电池       94              135              30%
--   星辰        5                5               0%
--
-- 「退货」这种高频短词，43 条里只能找到 3 条。所以必须自己做中文切分。
--
-- ------------------------------------------------------------
-- 二、为什么选了「双字切分（bigram）」而不是 pg_trgm
-- ------------------------------------------------------------
--
-- docs/04 §11.1 原本倾向 pg_trgm（理由是它是 PostgreSQL 自带扩展、零成本）。
-- 在真实语料上实测后这个推荐站不住 —— query = '退货要几天'：
--
--   方案                             召回    排序区分度   实测证据
--   pg_trgm word_similarity          ✅      ❌ 完全并列   4 条正确切片全是 0.3333
--   单字 + plainto_tsquery           ❌ 0 行  —          退 & 货 & 要 & 几 & 天，AND 必然空
--   双字 + OR + ts_rank               ✅      ✅          0.022244 / 0.021636 / 0.020686
--
-- pg_trgm 的结构性缺陷：它只生成 **3 字窗口**，而中文词大多是 2 字。
-- 查询「退货要几天」产生 6 个三元组，其中首尾补空格得到的
-- "  退" 和 "几天 " 在长文本中间**永远不可能出现**，
-- 所以最多只有 3 个可能命中。它只能当二元过滤器（相关 0.3333 / 不相关 0.0000），
-- **在相关集合内部没有任何排序能力**。
--
-- 这一条对 RRF 融合尤其致命：融合只取**排名**不取**分数**，
-- 并列时的顺序等于「按 id 排」，语义上完全没有意义 ——
-- 等于把关键词这一路废掉了。详见 ADR-020。
--
-- ------------------------------------------------------------
-- 三、为什么分词写在 Java 里，而不是 SQL 函数
-- ------------------------------------------------------------
--
-- 可以把 bigram 切分写成一个 IMMUTABLE 的 SQL 函数，那样 search_text
-- 也能变成生成列，回填就是 ALTER TABLE 的副产品。**没有这么做**，三个理由：
--
--   1. 分词逻辑会有 Java 和 SQL 两份，迟早不一致；
--   2. 丢掉「纯函数可单测」—— BigramCjkTokenizer 是阶段 4 最该被钉死的一段
--      逻辑，而 PL/pgSQL 只能在真库里测，和本项目「不起 Spring、直接 new
--      被测对象、毫秒级」的测试风格冲突；
--   3. ★ 技术上会撞墙：PostgreSQL **不允许生成列引用另一个生成列**。
--      search_text 一旦变成生成列，search_vector 就没法再从它派生，
--      两列只能合并成一个 —— 又回到表达式索引那条路上了。
--
-- 所以：Java 侧分词 → 写普通列 search_text → 数据库用生成列派生 search_vector。
-- 回填靠 POST /api/debug/kb/reindex（只保留一份分词逻辑，且分词器可替换）。
-- ============================================================


-- ============================================================
-- 四、加列
-- ============================================================

-- ① Java 侧分词器产出的「词元串」，空格分隔。
--    例：'退货要几天' → '退货 货要 要几 几天'
--         '星辰X1 电池' → '星辰 辰x x1 电池'
--
--    规则是「只在连续同类字符段内部生成词元，永不跨段」：
--      · CJK 段   → 切 2-gram
--      · ASCII/数字段 → 整体保留为一个词元（X1 → x1、5000mAh → 5000mah）
--      · 跨段     → 不生成任何词元
--    为什么强调「不跨段」：实测 to_tsvector 会把跨段切出来的
--    "1 " 退化成**裸的单字词元 1**，而裸单字在中文里是最高频词元，
--    OR 起来候选集直接爆炸（实测「星辰X1 电池」的候选集从 3.8% 涨到 36.6%）：
--      SELECT to_tsvector('simple','星辰 辰X X1 1 电 电池');
--      →  '1':4 'x1':3 '星辰':1 '电':5 '电池':6 '辰x':2      ← 裸单字出现了
--
--    体积预期：词元数量 ≈ 字符数，每个词元后跟一个空格，
--    所以本列约是原文的 2 倍字节（500 字切片 → 约 1000~1500 字符）。TEXT 无上限。
ALTER TABLE kb_chunk ADD COLUMN search_text TEXT;

COMMENT ON COLUMN kb_chunk.search_text IS
    '★ 中文分词后的词元串（空格分隔），不是原文。由 Java 侧 CjkTokenizer 生成，'
    '写入时同步维护。检索时拼成 tsquery 的 OR 链。参见 docs/05';

-- ② 从 search_text 派生出的 tsvector。
--
--    ★ 为什么用「生成列」而不是「表达式索引」：
--
--    表达式索引要求 WHERE / ORDER BY 里的表达式与索引定义**字面完全一致**，
--    差一个引号（'simple' vs "simple"）、差一个空格，索引就**静默不生效**，
--    退化成全表扫描 —— 不报错、不警告，只是慢。这是最难排查的一类问题。
--    生成列没有这个陷阱。
--
--    而且 ts_rank 也需要 tsvector：表达式索引下得写
--    ts_rank(to_tsvector('simple', search_text), q)，候选集内每行重算一遍；
--    生成列可以直接读存储的列值。
--
--    ★ 'simple' 这个参数**必须显式写**，不能省。
--      to_tsvector(text) 单参数版本是 STABLE（依赖 default_text_search_config），
--      STABLE 的函数**不允许用在生成列里**，迁移会直接失败。
--      to_tsvector(regconfig, text) 才是 IMMUTABLE。
--      这是好事 —— 写漏了会失败得响亮，而不是静默出错。
--
--    ★ search_text 为 NULL 时本列也是 NULL。
--      注意 to_tsvector('simple','') **不是 NULL**，而是空 tsvector，
--      所以「忘了写 search_text」和「写了空串」要靠查 search_text 才能区分。
--      覆盖率探针见 GET /api/debug/kb/search-text-stats。
--
--    代价：多存一份 tsvector；执行本语句会**重写整张表**
--    （当前 1652 行，毫秒级，可忽略）。
ALTER TABLE kb_chunk ADD COLUMN search_vector tsvector
    GENERATED ALWAYS AS (to_tsvector('simple', search_text)) STORED;

COMMENT ON COLUMN kb_chunk.search_vector IS
    '从 search_text 自动派生的 tsvector（''simple'' 配置）。生成列，应用不要直接写。'
    '关键词检索的 GIN 索引建在这一列上';


-- ============================================================
-- 五、GIN 索引
-- ============================================================
--
-- GIN 是倒排索引（词元 → 行号），正是全文检索需要的结构。
-- （对比 B-tree：那是「值的顺序」索引，对「包含某个词」这种查询无能为力。）
--
-- ⚠️ 索引建在 search_vector 上、而不是在 search_text 上，有两个原因：
--    1. 查询条件是 search_vector @@ tsquery，索引必须匹配这个表达式；
--    2. search_text 上的索引没法加速 @@ —— 数据库还得先把它转成 tsvector。
CREATE INDEX idx_kb_chunk_search ON kb_chunk USING GIN (search_vector);


