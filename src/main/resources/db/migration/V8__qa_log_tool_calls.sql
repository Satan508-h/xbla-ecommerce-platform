-- ============================================================
-- V8 —— qa_log 增加 tool_calls（阶段 5.8 的工具调用记录）
--
-- ⚠️ V1~V7 一个字都不能改（validate-on-migrate: true，改了起不来）。本文件是新增。
--
-- 只加一列，不建索引 —— 见下面第五节的说明。
-- ============================================================


-- ============================================================
-- 一、为什么要记它
-- ============================================================
--
-- 阶段 5.8 让「我的订单到哪了」这类问题走 MCP 工具而不是知识库检索。
-- 于是出现了一类**全新的失败**：
--
--     用户问「我的订单到哪了」→ 回答是错的（或者干脆是编的）
--     但 qa_log 上看起来一切正常：status=1、有 provider、有 final_answer
--
-- 要归因，第一件必须知道的事是：**这次到底调工具了没有？**
--
--   ① 一次都没调   → 工具接入没生效（意图没分对 / 列表没拉到 / 轮次是 0）
--   ② 调了但结果不对 → 工具实现或参数的问题
--   ③ 调了但模型没用它 → Prompt 的问题
--
-- 这三种情况的优化方向**完全不同**，而**没有这一列时它们在数据上
-- 长得一模一样**。这和 retrieval_detail 存在的理由是同一条
-- （见 V5 里那一列的注释：「召回失败是因为向量检索没找到，
-- 还是重排排错了，还是切分粒度不对」）。
--
-- ⚠️ 顺带说明一个容易被忽略的坑：
--   阶段 5.7 已经接入了 MCP **Server**，但那时还没有 Client，
--   所以 5.7 之后、5.8 之前的 qa_log 里这一列**全是 NULL** ——
--   和「工具没被调用」看起来一样。判断依据是配置快照里的
--   xbla.mcp.client.enabled 和部署时间，不是这一列本身。


-- ============================================================
-- 二、列定义
-- ============================================================

ALTER TABLE qa_log ADD COLUMN tool_calls JSONB;

COMMENT ON COLUMN qa_log.tool_calls IS
    '★本次问答实际发生的 MCP 工具调用，按发生顺序。NULL = 一次都没调（不是空数组）。'
    '元素形状：{round, tool, isError, detail}。'
    '★ 不存工具返回的内容 —— 那是订单数据，没有理由在这里再存一份，'
    '要复现就按同一个参数重调一次工具（它是只读的）。';


-- ============================================================
-- 三、为什么是 NULL 而不是空数组
-- ============================================================
--
-- 和 degradation_events / references 的既有约定完全一致：
--
--     NULL      = 这件事**没有发生**（这次问答根本没走工具路径）
--     []        = 发生了，但结果是空的
--
-- 而在工具这个场景里，「没发生」和「发生了但没调成」**确实是两件事**：
-- 前者说明意图分类没把它分到 TOOL 类（要去看意图树和分类日志），
-- 后者说明分对了但工具链路有问题（要去看 MCP 的日志）。
--
-- ⚠️ 把两者都写成 [] 会让「工具接入上线了但一次都没跑起来」
-- 这种最要命的部署问题**看起来完全正常**：
-- 每一行都是合法的 JSON、每一个字段都有值，只是全是空的。
--
-- 序列化时由 Java 侧保证（baseLog 里 chunks/trace 为 null → 这一列写 NULL），
-- 和 references 是同一个函数模式。


-- ============================================================
-- 四、为什么 isError 要单独存，而不是只存 tool 名
-- ============================================================
--
-- 「调了 query_order_status」这一条信息**不足以**归因。
-- 还需要知道工具是给出答案了，还是报告失败了。
--
-- ★ 注意这里的 isError 是 5.7 定义的那个语义：
--   **「工具有没有给出答案」，不是「答案是不是空的」**
--   （见 QueryOrderStatusTool 的类注释）。
--   所以「查无此单」是 isError=false —— 它是个答案。
--
-- 于是这一列能直接回答几个统计问题：
--   SELECT tool, count(*) FROM qa_log,
--          jsonb_array_elements(tool_calls) t
--    WHERE tool_calls IS NOT NULL GROUP BY tool;
--
--   -- 失败率高的是哪个工具
--   ... WHERE (t->>'isError')::boolean GROUP BY tool;


-- ============================================================
-- 五、为什么不加索引
-- ============================================================
--
-- qa_log 是**写入最频繁**的表（每一次问答一行），
-- 而这几列只用于**事后分析**，不在任何在线路径上。
--
-- JSONB 上的 GIN 索引对写入有实打实的代价，而它换来的查询加速
-- 在这个项目的数据量下毫无意义（阶段 7 跑一次全表扫描也就几百毫秒）。
--
-- ★ 这和 retrieval_detail 不加索引是同一个决定：
--   **分析用的列，让分析的时候慢一点，不要在写入路径上一直付钱。**
--
-- 真到了需要的时候再加 —— 那时也应该先确认 qa_log 有没有按时间分区，
-- 分区带来的收益比索引大得多。


-- ============================================================
-- 六、和「所有写操作可追溯到 qa_log」这条约定的关系
-- ============================================================
--
-- CLAUDE.md 第 4 条：所有对数据库的写操作都要能追溯到 qa_log。
--
-- 工具调用**本身不写库**（query_order_status 是纯只读查询），
-- 所以严格按字面它不需要被记录。但它的**读结果**影响了最终回答 ——
-- 而「这个回答依据了什么」正是 qa_log 要回答的问题
-- （references 记的是「引用了哪些切片」，同理）。
--
-- 所以这一列和 references 是同一个角色：
-- **记录这次回答的输入证据**，只不过一个是静态文档、一个是实时数据。
