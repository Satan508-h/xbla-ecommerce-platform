-- ============================================================
-- V12 · eval_question 支持「工具题」与「本就没有检索目标的题」（阶段 7 · 7.1）
--
-- ⚠️ V1~V11 一个字都不能改 —— `validate-on-migrate: true` 会让应用起不来。
--    所以这里只做 ALTER。
--
-- 两件事：
--   ① user_id BIGINT NULL                —— 工具题要用它去调 MCP 工具
--   ② expect_no_retrieval BOOLEAN NOT NULL DEFAULT false
--                                        —— 显式声明「这道题本来就没有 gold」
-- ============================================================


-- ============================================================
-- 一、为什么需要 user_id —— 工具题没有身份就必然失败
-- ============================================================
--
-- 阶段 7 的题库里有 15 道题问的是【实时数据】而不是知识库：
--
--   订单状态（6）     「我的订单到哪了」      → query_order_status
--   库存查询（5）     「华为 Mate Ultra 还有货吗」→ query_inventory
--   我的优惠券（4）   「我有哪些优惠券」       → query_my_coupons
--
-- 这三个意图在意图树里是 retrieval: TOOL —— 它们【不检索知识库】，
-- 答案来自 MCP 工具。而工具的身份只能来自 McpToolContext（ADR-054），
-- 参数里没有 user_id（那是模型可控的越权入口）。
--
-- ★★ 所以身份必须由【调用方】带进去：跑题器要发
--    `X-Xbla-User-Id: <id>` 这个头。而那个 id 得从哪儿来？
--    只能从题库里来 —— 这一列就是它的出处。
--
-- ⚠️ 不加这一列的后果不是报错，而是**静默的**：
--    工具收到空身份 → 返回「未登录」→ 模型如实转述 →
--    评测报告显示「订单类问题 0% 正确」，而真正的原因是评测自身
--    没带身份。★ 这类失败和「模型不行」在报告上长得一模一样。
--
-- ★ 列可空：另外 144 道题（知识库题与兜底题）不需要身份，
--   给它们填一个值反而是噪声（并会让人以为「所有题都有用户」）。


-- ============================================================
-- 二、为什么需要 expect_no_retrieval —— 空 gold 必须是显式的
-- ============================================================
--
-- 上面那 15 道工具题，加上兜底（7）与澄清（6）两道非业务分支，
-- 一共 28 道题**没有 gold** —— 它们的正确答案不在知识库里，
-- 检索指标的分母里也不该有它们（docs/06：空 gold 题单独一桶）。
--
-- 但「空 gold」和「漏写锚点」在数据上长得一模一样（都是空数组）。
-- 写题时忘了一个 anchors 段，加载器如果不报错，那道题就会
-- **静默退出检索指标**：题数少一道看不出来，指标也不会错，
-- 只是那道题再也不测任何东西了 —— 同 ADR-036 那条「静默漏跑」。
--
-- ★ 所以分成两种表达：
--     写了 anchors                → 必须有锚点，且必须唯一命中
--     写 expect_no_retrieval: true → 必须【没有】anchors，gold 为空
--     两个都没有                  → 加载失败（并告诉写题的人有第三种可能）
--   ★ 两个都写 → 也失败：声明「不检索」却又给了锚点，是自相矛盾。
--
-- ⚠️ 为什么这一列用 DEFAULT false（而 V11 的 question_set 刻意不用 DEFAULT）：
--   因为两者的**默认方向风险相反**。
--     question_set：任何默认值都在替写题的人断言一件事，断言错了没人知道
--     expect_no_retrieval：false 是保守值 —— 它把这道题算进检索指标，
--       而 gold 为空时那个指标会显示 0 分（吵），不会静默变好
--   ★ 一句话：**默认值要往「会让问题暴露出来」的方向取。**
--
-- ⚠️ 这一列的存在还有一个用途：报告端点在算检索指标时可以
--   `WHERE NOT expect_no_retrieval` 来排除，而不必去猜
--   「空数组是声明的还是写错了」—— 数据自己说清楚。


-- ============================================================
-- 三、改动
-- ============================================================

ALTER TABLE eval_question ADD COLUMN user_id BIGINT;

ALTER TABLE eval_question ADD COLUMN expect_no_retrieval BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN eval_question.user_id IS
    '工具类题目（retrieval=TOOL）要用哪个用户身份去调 MCP 工具。'
    '★★ 身份只能从这里读、由跑题器写进 X-Xbla-User-Id 头；'
    '绝不能变成工具的参数（ADR-054：那是模型可控的越权入口）。'
    '⚠️ 可空：知识库题与兜底题不需要身份，填了是噪声。';

COMMENT ON COLUMN eval_question.expect_no_retrieval IS
    '★ 显式声明「这道题本来就没有检索目标」（工具调用 / 兜底 / 澄清）。'
    'true=必须没有 anchors，expected_chunk_ids 为空；'
    'false=必须有 anchors 且唯一命中（漏写会加载失败）。'
    '检索类指标应排除这些题（docs/06：空 gold 单独一桶，不进分母）。'
    '★ 默认 false 是保守方向：把题留在检索指标里，空 gold 会显示 0 分（吵），不会静默。';

-- ★ 不加索引：这张表不到 200 行，只在 reload 与报告端点被扫（同 V9 / V11 的理由）。
