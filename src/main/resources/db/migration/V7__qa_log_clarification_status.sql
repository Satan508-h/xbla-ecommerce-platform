-- ============================================================
-- V7 · 给 qa_log.status 增加第三个取值：澄清反问（阶段 5.3）
--
-- ⚠️ V1~V6 一个字都不能改 —— `validate-on-migrate: true` 会让应用起不来。
--    所以这里只做 ALTER，不回头改 V5。
--
-- ------------------------------------------------------------
-- 为什么需要第三个值
--
-- V5 里 status 只有两个取值，它们的语义是：
--     1 = 成功生成了答案
--     2 = 模型链路失败
--
-- 而阶段 5.3 的「澄清反问」两种都不是：
--     · 它【没有生成答案】—— 系统判定用户那句话信息不足，
--       于是不检索、不调生成模型，直接反问一句
--     · 它也【没有失败】—— 这恰恰是系统正确工作的表现
--
-- 硬塞进 1 或 2 都会污染阶段 7 的统计：
--
--   塞进 1（成功）
--     → qa_log.final_answer 里会躺着一句「你是想问哪款商品呢？」
--     → 它看起来像一条正常回答，于是
--       答案质量类指标（RAGAS 的 faithfulness / answer_relevancy）
--       会给它打分 —— 而它根本不是答案，是一个问题
--     → 检索类指标（Recall / HitRate）会把它算成「没召回到」，
--       凭空拉低召回率
--
--   塞进 2（失败）
--     → 阶段 7 会把「系统正确识别出该反问」统计成「模型挂了」
--     → 这正是 docs/05 §五 反复强调的那类归因错乱：
--       两种修法完全相反的问题，在数据上长得一模一样
--
-- ★ 这个项目在同一个坑上摔过不止一次了：
--     · 阶段 4：检索的异常差点被记成「模型挂了」（R3）
--     · 阶段 5.2：分类失败的三种原因必须分开（ADR-038）
--     · 阶段 5.3：兜底和澄清必须分成两个 role（ADR-035 的延伸）
--   规律是一样的 —— **能让两种不同性质的东西共用一个值时，
--   统计迟早会悄悄错，而且从数据上看不出来。**
--
-- ------------------------------------------------------------
-- 为什么不复用 intent = 'NEEDS_CLARIFICATION' 来筛
--
-- 那需要阶段 7 每处统计都写 `WHERE status = 1 AND intent <> 'NEEDS_CLARIFICATION'`。
-- 而「每处都要记得加一个条件」正是最容易漏的形态：
-- 漏了不报错，只是数字偏低，没人看得出来。
-- 变成 status 的一个取值之后，`WHERE status = 1` 天然就是对的。
-- ============================================================

ALTER TABLE qa_log DROP CONSTRAINT ck_qa_log_status;

ALTER TABLE qa_log ADD CONSTRAINT ck_qa_log_status CHECK (status IN (1, 2, 3));

COMMENT ON COLUMN qa_log.status IS
    '1成功生成答案 2模型链路失败 3澄清反问（未生成答案，也未失败）';

-- ★ 阶段 7 的检索类与答案质量类指标一律【只统计 status = 1】：
--     澄清反问没有答案可评（status=3），失败根本没有答案（status=2）。
--
-- ⚠️ 这里没有建一个 `WHERE status = 1` 的视图 —— 视图里写 SELECT *
--    会在以后给 qa_log 加列时静默变陈旧（列清单被冻结在创建那一刻）。
--    取值本身定义在 Java 侧：`QaLog.STATUS_SUCCESS` / `STATUS_FAILED` /
--    `STATUS_CLARIFY`，代码里不出现裸数字。
