-- ============================================================
-- V17 · eval_question.expect_clarify （阶段 9.6a）
--
-- 「这一轮的提问【该不该】被澄清闸门反问」的 gold。
--
-- ------------------------------------------------------------
-- 一、为什么需要它
--
-- 9.6 的多轮澄清指标分三层，第 ① 层是「首轮反问发生了没」。
-- ★★ 而这一层原本【没有 gold】—— 题库里没有任何字段回答得了它：
--
--     单轮题的 gold intent 就是这一轮的意图 ⇒ 是不是澄清码就是答案（能推）
--     多轮题的 gold intent 描述的是【末轮】  ⇒ 对首轮毫无信息（推不出来）
--
-- 实测（2026-09-26，stage9-clarify-multi 8 题 × 3 次）：
--   ① = 12/24 = 50%，而其中 **3 道题的首轮不反问是对的**
--   （问的是退货政策，本来就不依赖商品）—— 没有 gold 就分不出
--   「系统少反问了一次」和「我的场景前提不成立」。
--
-- ------------------------------------------------------------
-- 二、★★ 为什么是【可空】的，而不是像 expect_no_retrieval 那样 NOT NULL DEFAULT false
--
-- 那一列的默认值 false 对**每一道题**都恰好成立，所以能当默认值：
-- 它表达的是「把这道题留在检索指标里」（往「会让问题暴露出来」的方向取）。
--
-- ★★ 这一列不行。DEFAULT false 会把「没标注」和「标注为不该反问」合并成
-- 一个值 —— 而那正是全库那条约定禁掉的事（「没有发生」和「发生了但是空的」
-- 必须能区分开），只不过这里换成了「没标注」和「标注为 false」。
--
-- 而且合并出来的那个值【还是错的】：多轮题的 false 会与「这一道本来就不该
-- 反问」长得一模一样，于是一道**该反问而没标**的题，在报告里会静默地
-- 变成一次「不该反问却反问了」的假阳 —— 一个指向反方向的结论。
--
-- 所以三态：
--
--     NULL  → 【没显式声明】⇒ 报告判它「不可判」，排除出 ① 的分子分母
--     true  → 这一轮该被反问
--     false → 这一轮不该被反问
--
-- ★★ 报告【不做任何回落】。唯一能回落的来源是 gold intent（单轮题上恰好正确），
--    而这一段只处理多轮题 —— 所以那一格必须由人**显式写出来**。
--
-- ------------------------------------------------------------
-- 三、⚠️ 这一列的清除必须能落库
--
-- MyBatis-Plus 的 updateById 默认策略是 NOT_NULL —— **null 字段被静默跳过**。
-- 也就是说：把 expect_clarify 从 yml 里删掉，库里的旧值【不会被清掉】，
-- 而报告会继续用那个陈旧的显式值。同 9.4 的坑 41（清空一列必须显式 set）。
-- ⇒ 实体上挂了 @TableField(updateStrategy = ALWAYS)，见 EvalQuestion#expectClarify。
-- ============================================================

ALTER TABLE eval_question
    ADD COLUMN IF NOT EXISTS expect_clarify BOOLEAN;

COMMENT ON COLUMN eval_question.expect_clarify IS
    '多轮题【第 1 轮】该不该被澄清闸门反问（阶段 9.6a）。'
    'NULL = 没显式声明 ⇒ 报告判「不可判」并把它排除出 ① 的分子分母。'
    '★ 只认显式值，不做任何回落：多轮题的 gold intent 描述的是【末轮】，'
    '拿它给首轮下结论必然错 —— 而猜出来的错值会和真值长得一样地印进报告。'
    '⚠️ 不是 NOT NULL DEFAULT false：「没标注」与「标注为不该反问」是两件事，'
    '合并之后，一道该反问而没标的题会静默变成一次假阳（指向反方向的结论）。';
