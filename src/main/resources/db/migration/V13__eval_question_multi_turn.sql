-- ============================================================
-- V13 · eval_question 支持「多轮题」（阶段 7 · 7.1 批次 6）
--
-- ⚠️ V1~V12 一个字都不能改 —— `validate-on-migrate: true` 会让应用起不来。
--    所以这里只做 ALTER。
--
-- 两件事：
--   ① turns JSONB                —— 多轮题的完整轮次（单轮题为 NULL）
--   ② standalone_question TEXT   —— 「把最后一轮单独说该怎么说」
--   外加两条 CHECK 约束，把「多轮题必须是多轮的」交给数据库执行
-- ============================================================


-- ============================================================
-- 一、★★ 为什么多轮题必须单独一套 —— 先说清楚它要测什么
-- ============================================================
--
-- 阶段 7 的评审揪出过一个洞（洞 6）：
--
--   「分类器的输入【按决策不含历史】，所以『追问轮的意图』不是一个
--     可测量的量。」
--
-- ★ 写这一批题之前，我把这条决策在代码里核了一遍，结果比评审说的更彻底：
--
--     ChatServiceImpl:177   intentClassifier.classify(question)      ← 只有这一句
--     ChatServiceImpl:213   retrievalPipeline.retrieve(question, …)  ← 也只有这一句
--
--   分类不看历史是【写在 ADR-046 里的决策】（5.2 的 95% 就建立在它之上）。
--   而**检索也不看历史** —— 这一条不在任何 ADR 里，是既成事实。
--
--   ★★ 也就是说：用户说「那它游泳能戴吗」，
--      检索层收到的是字面的「那它游泳能戴吗」这七个字，一个「它」字都解不开。
--
--   这件事在第 5 阶段没有任何东西能让它可见 —— 因为所有验证都是单轮的。
--   多轮题存在的【唯一】理由就是让它可见：
--
--     单轮题测的是   「这句话的意思能不能被找到」
--     多轮题测的是   「上一句话建立起来的那个东西，还在不在」
--
-- ⚠️ 所以这一套题的数字天生比单轮那套【难看】，而那不是 bug。
--    报告里必须把原因写在数字旁边，否则读者会以为检索退化了。


-- ============================================================
-- 二、turns —— 为什么最后一轮【不】再单独存一个 question 字段
-- ============================================================
--
-- 一道多轮题长这样：
--
--     turns:
--       - 小米手环 8 防水吗
--       - 那它游泳能戴吗
--
-- 而题库里**没有** `question:` 这一行 —— 最后一轮就是被测量那一轮，
-- 它已经在 turns 的末尾了。加载器把它取出来填进 `question` 列。
--
-- ★ 为什么不两处都写（turns 里一份、question 里一份）：
--   那是同一个事实的两个来源，而两个来源【一定会**漂**】——
--   改了一处忘了另一处时：
--
--     改了 question、没改 turns  →  跑题器按 turns 发问，报告按 question 对账，
--                                   对账失败（还好，吵）
--     改了 turns、没改 question  →  报告里那一行的问题文本与实际所问不符，
--                                   而 qa_log.eval_question_no 是对的 ——
--                                   ★ 没人会发现，而报告从此描述错了东西
--
--   加载器把第二种情况直接变成报错：**同时写 turns 和 question 是自相矛盾**
--   （同 V12 那条「同时写 anchors 和 expect_no_retrieval」的三态纪律）。


-- ============================================================
-- 三、standalone_question —— 它是【gold】，不是注释
-- ============================================================
--
-- 「把最后一轮单独说该怎么说」—— 例如上面那道题：
--
--     standalone_question: 小米手环 8 能戴着游泳吗
--
-- ★★ 这道题的 intent / anchors / expected_answer 【全部按这一句标】。
--
--   理由：用户真正想问的是这个意思，「那它游泳能戴吗」只是它在上下文里的
--   一种省略说法。如果 gold 反而按「分类器看到的那七个字」来标，
--   这一套题就退化成单轮题集的一个副本 —— 它测的是「分类器知不知道
--   自己缺信息」，而单轮集里那 6 道澄清题已经测过了。
--
--   按 standalone 标，报告里会得到两个有意义的数：
--
--     追问轮意图准确率   低   ← 每个点都能解释：分类器看不到「它」是什么
--     追问轮检索覆盖率   低   ← ★ 这个数是新发现，它第一次把
--                                 「检索也不看历史」变成可测量的东西
--
-- ⚠️ 它必须是一【列】而不是写在 notes 里的散文：
--   notes 给人读，这一列给跑题器读（T3 会拿它做「单独问 vs 追问」的对照），
--   两者的读者不同，混在一起会让人以为它只是文案。
--
-- ⚠️ 它与 turns 同生同死 —— 见下面第二条 CHECK。


-- ============================================================
-- 四、为什么这两条约束交给数据库而不是只写在加载器里
-- ============================================================
--
-- 加载器当然会校验（它已经有三态那套）。但这两条额外写进 CHECK，
-- 理由和 V4 把向量维度写成 vector(1024) 是同一条：
--
--   「多轮题必须真的有多轮」这件事，不该只靠【Java 里那句 if】成立。
--   手写一条 UPDATE、写个脚本批量补数据、将来换个加载器 ——
--   都会绕过那句 if，而数据库约束绕不过去。
--   ★ 症状对照：向量维度写错不会立刻出事，它污染检索；
--     多轮题只有一轮不会立刻出事，它让「多轮指标」里混进单轮数据。
--     两者的共同点是【都不会报错】。
--
-- ⚠️ 约束成立的前提：现有 179 行 turns / standalone_question 都是 NULL，
--    两条 CHECK 对它们都为真（NULL 不参与比较 —— 这里靠 IS NULL 显式判）。


-- ============================================================
-- 五、改动
-- ============================================================

ALTER TABLE eval_question ADD COLUMN turns JSONB;

ALTER TABLE eval_question ADD COLUMN standalone_question TEXT;

-- ① 「多轮」必须真的是多轮：一个数组，且至少两轮。
--    ★ 只有一轮的条目请写进单轮题库 —— 那不是多轮题，是一道写法绕了点儿的单轮题，
--      放进这一套会让它的数字被当成「多轮能力」读。
ALTER TABLE eval_question ADD CONSTRAINT ck_eval_question_turns_is_array
    CHECK (
        turns IS NULL
        OR (jsonb_typeof(turns) = 'array' AND jsonb_array_length(turns) >= 2)
    );

-- ② turns 与 standalone_question 同生同死。
--    ★ 只有 turns 没有 standalone_question → 这题没有 gold（不知道按哪句话标）；
--      只有 standalone_question 没有 turns → 那它就是一道单轮题，
--      该写的字段是 question，写成 standalone_question 是搞错了角色。
--    两种半成品都在这里被挡住，不留「看起来像多轮题」的中间态。
ALTER TABLE eval_question ADD CONSTRAINT ck_eval_question_multi_turn_shape
    CHECK ((turns IS NULL) = (standalone_question IS NULL));

COMMENT ON COLUMN eval_question.turns IS
    '多轮题的完整轮次（JSON 字符串数组，按时间顺序）。★ 最后一轮=被测量那一轮，'
    '加载器把它填进 question 列 —— 所以题库里【不写】question 字段（同写即报错）。'
    '单轮题为 NULL。约束：必须是数组且 >=2 轮。'
    '★ 这一列存在的唯一理由是让「检索也不看历史」这件事可测量。';

COMMENT ON COLUMN eval_question.standalone_question IS
    '★ 「把最后一轮单独说该怎么说」—— 本题的 intent/anchors/expected_answer '
    '【全部按这一句标】。用户真正想问的是这个意思，追问句只是它在上下文里的省略说法。'
    '⚠️ 它是给跑题器读的 gold（T3 做「单独问 vs 追问」的对照），不是注释。'
    '与 turns 同生同死：turns 非空则它必须非空，反之亦然。';

-- ★ 不加索引：这张表不到 200 行，只在 reload 与报告端点被扫（同 V9 / V11 / V12 的理由）。
--   ★ 也【不】给 turns 加 GIN 索引：没有任何查询要钻进 turns 里面，
--     而 V8 已经记过一次「JSONB 的 GIN 索引对写入有实打实的代价」。
