-- ============================================================
-- V18 · user_event（阶段 9.6b · 在线指标）
--
-- ⚠️ V1~V17 一个字都不能改 —— `validate-on-migrate: true` 会让应用起不来。
--    所以这里只做 CREATE。
--
-- 一件事：
--   建一张【浏览器行为】表。它是本项目第一张不由服务端写、而由
--   前端上报的数据 —— 这个来源的性质决定了下面几乎每一条设计。
-- ============================================================


-- ============================================================
-- 一、★★★ 为什么必须新开一张表，而不是往 qa_log 上加列
-- ============================================================
--
-- qa_log 的一行 = 【一次问答】，它是服务端对「我做了什么」的记录：
-- 意图、检索、五段延迟、成本、工具调用 —— 全部由服务端观察得到。
--
-- 而「用户点开了哪条引用」「他觉得这个回答好不好」，
-- 【服务端根本观察不到】。前端不发回来，它就永远不存在。
--
-- ★★ 所以这不是「qa_log 少了几列」，是【一条新的数据来源】：
--
--     qa_log      服务端观察到的「问答」
--     user_event  浏览器声明的「行为」
--
-- ⇒ 两者的可信度【不一样】，而这件事必须写在表上，不能只在文档里。
--    最要紧的一条：user_id 那一列的处置与 qa_log.user_id 同侧
--    （原样记、无外键），理由见第三节。
--
--
-- ============================================================
-- 二、★★★ event_no 是【幂等键】，而它是冲着一个具体的失败模式去的
-- ============================================================
--
-- 浏览器会重试，而【重复计数是最难发现的指标错误】：
-- 它不报错、不告警，只是让每一个率都偏高一点点，而那个偏差
-- 长得和「用户真的更活跃」一模一样。
--
-- ★ 所以幂等不能靠「前端只发一次」这种约定 —— 那个约定在
--   「用户双击」「页面被恢复」「网络超时后重发」这三种情况下都会破。
--   只能让重复的那一条【在数据库层插不进去】：
--
--     UNIQUE (event_no)  +  INSERT ... ON CONFLICT DO NOTHING
--
--   ⇒ 同一个事件无论被投递几次，表里恒为一行。
--     这个性质让上报端点【可以安全地重试】，也让前端的 sendBeacon
--     不需要任何去重逻辑（浏览器关掉页面就发，不管结果）。
--
-- ★ event_no 由【前端】生成（crypto.randomUUID），不是数据库序列。
--   服务端序列做不到这件事 —— 第二次请求会拿到一个新的 id，
--   于是同一件事被记两次，而两次都「合法」。
--
--
-- ============================================================
-- 三、★★★ user_id 刻意【不加外键】—— 与 qa_log.user_id 同侧
-- ============================================================
--
-- ADR-091 立了一张表，本表照抄它的判断：
--
--   chat_session.user_id  有 FK，写入前核对 app_user，查不到记 NULL
--   qa_log.user_id        无 FK，原样记
--
-- 本表选【后者】，而且是更硬的理由：qa_log 至少还是服务端写的，
-- 本表的值【直接来自浏览器】—— 前端那个「身份 ID」输入框可以填任何东西。
--
-- ★★ 加了 FK 会怎样：一个伪造的值让 INSERT 直接失败 ⇒
--    整批埋点写不进去，而埋点【绝不能影响主链路】。
--    更坏的是它是静默的 —— 那个用户的一切行为凭空消失，
--    而看起来只是「他今天没点」。
--
-- ★ 代价照旧要写下来：这一列【可能不存在于 app_user】，
--   任何 `JOIN app_user` 都会静默丢行。要人读的统计必须用 LEFT JOIN，
--   或者干脆不 JOIN（本表的聚合就不 JOIN）。
--
--
-- ============================================================
-- 四、★★ occurred_at 与 received_at 是【两列】，不是一个
-- ============================================================
--
--   occurred_at   客户端报的「他什么时候点的」
--   received_at   服务端写的「我们什么时候收到的」
--
-- ★ 只留一列的话，两种完全不同的故障在数据上【长得一模一样】：
--
--     客户端时钟偏了 10 分钟   →  看起来像「网络慢了 10 分钟」
--     网络真的慢了 10 分钟     →  看起来像「客户端时钟偏了」
--
--   而这两件事的修法相反（一个去查用户设备，一个去查链路）。
--
-- ★ 时间窗口口径（「24h 内的点击」）要的是【前者】——
--   用户什么时候点的，不是我们什么时候知道的。所以聚合按 occurred_at 切。
--
-- ★ `received_at` 就是这张表在别处叫 `created_at` 的那一列，
--   这里改名是因为它在本表承担一个【对比语义】。
--   ⚠️ 所以本表【没有】名叫 created_at 的列，这不是漏了。
--
--
-- ============================================================
-- 五、trace_id 是唯一把行为挂回问答的骨
-- ============================================================
--
-- 没有它，埋点只是一堆孤立的点击，「引用点击率」的分母（有引用的回答）
-- 和分子（被点开的引用）就永远对不上。
--
-- ★ 可空，而且【历史消息那一格必然是空】：
--   chat_message 里没有 trace_id（阶段 8 拍板「技术面板只服务当前回答」），
--   所以从历史会话里翻出来的引用根本点不开，也就不会产生事件。
--   可空不是宽容，是那张形状表里的一格。
--
--
-- ============================================================
-- 六、payload 存差异部分，不为每种事件加列
-- ============================================================
--
-- ref_click 要带 chunkId / no，feedback 要带 vote —— 这两种形状不同。
-- 加列的话每来一种事件就 ALTER 一次，而 ALTER 在生产上是有代价的。
--
-- ⚠️ 代价是读的时候要写 `payload ->> 'vote'`，而它是 **text**，
--    不是 jsonb —— 同 docs/10 坑 24 那一类（分不清「键不存在」和「键是 null」）。
--    好在本表的 payload 是我们自己写的，形状可控。
--
--
-- ============================================================
-- 七、不加 deleted，也没有 eval_run_id
-- ============================================================
--
-- 【不加 deleted】：本表是【追加型事实】—— 一次点击发生过就是发生过。
--   软删在这里没有语义（不像商品下架、切片下线那种「现在不生效了」）。
--
-- 【不加 eval_run_id】：★★ 这是一个【有前提】的省略，写下来是为了让它可被证伪：
--   评测流量（eval_run.py）直接打 /api/chat，【不经过浏览器】，
--   所以它不产生 sendBeacon ⇒ 本表天然只有真实流量。
--
--   ⚠️ 这个前提会在「将来有人用 Playwright / 无头浏览器跑评测」时失效。
--      那时本表会混进评测行为，而且【没有任何判据会报警】——
--      到那一天必须补 eval_run_id 列，或者让跑题器带上一个可识别的标记。
--   ★ 落在 SQL 上的防线：所有【要 JOIN qa_log】的聚合，仍然按
--     `qa_log.eval_run_id IS NULL` 过滤（ADR-086 推广）。
--     本表自己的纯计数（「一共点了几次」）没有分母，也就不需要那道筛子。
--
--
-- ============================================================
-- 八、索引
-- ============================================================
--
--   uk_user_event_no        UNIQUE(event_no)  —— 正确性，不是性能（见第二节）
--   idx_user_event_type_time (event_type, occurred_at DESC)
--                           —— 聚合的固定形状：按类型 + 时间窗切
--   idx_user_event_trace    (trace_id)        —— 把一次回答的行为捞回来
--
-- ★ 没有单独的 occurred_at 索引：本表的读全是「某个类型 + 某个窗口」，
--   上面那个组合索引已经覆盖；而不带类型的全表扫，在演示规模上是免费的。
-- ============================================================

CREATE TABLE user_event
(
    id          BIGSERIAL   PRIMARY KEY,

    -- ★ 幂等键，前端生成。见第二节 —— 唯一约束是【正确性】保证，不是调优
    event_no    VARCHAR(64) NOT NULL,

    -- ★ 白名单由服务端强制（EventController）。不认识的类型在入口就被丢弃，
    --   所以库里的取值集合是可控的；这一列【不适合作分类维度】的自由文本
    event_type  VARCHAR(32) NOT NULL,

    -- ★ 无外键。见第三节 —— 这一列可能不存在于 app_user，JOIN 会静默丢行
    user_id     BIGINT,

    session_no  VARCHAR(64),

    -- ★ 唯一把行为挂回 qa_log 的骨。历史消息那一格必然为 NULL，见第五节
    trace_id    VARCHAR(64),

    -- 事件各自的差异部分（ref_click → {chunkId, no}；feedback → {vote}）
    payload     JSONB,

    -- ★ 客户端报的「什么时候点的」—— 窗口口径按它切，见第四节
    occurred_at TIMESTAMPTZ NOT NULL,

    -- ★ 服务端写的「什么时候收到的」。它同时是这张表的 created_at
    received_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE user_event IS
    '浏览器行为事件（阶段 9.6b）。★ 本项目第一张【前端上报】的表 —— '
    '与 qa_log（服务端观察到的问答）是两种可信度不同的数据来源，不要混着解释。';

COMMENT ON COLUMN user_event.event_no IS
    '幂等键，前端用 crypto.randomUUID 生成。★★ 唯一约束是【正确性】保证：'
    '重复计数不报错、不告警，只让每个率都偏高一点点，而那个偏差长得像「用户更活跃」。';

COMMENT ON COLUMN user_event.event_type IS
    '事件类型。服务端白名单强制（不认识的直接丢弃），当前：ref_click / feedback。';

COMMENT ON COLUMN user_event.user_id IS
    '★★ 无外键，原样记（与 qa_log.user_id 同侧，见 ADR-091）。'
    '值是浏览器直接报上来的，前端可以填任何东西 —— 加 FK 会让一次伪造打挂整批埋点。'
    '⚠️ 代价：它可能不存在于 app_user，`JOIN app_user` 会静默丢行，要 LEFT JOIN 或不 JOIN。';

COMMENT ON COLUMN user_event.trace_id IS
    '关联 qa_log 的唯一骨。「引用点击率」的分子分母靠它对上。'
    '★ 历史消息里的引用没有 trace_id（chat_message 没存），那一格恒为 NULL。';

COMMENT ON COLUMN user_event.payload IS
    '事件差异部分。⚠️ 读的时候 `payload ->> ''vote''` 出来是 text 不是 jsonb。';

COMMENT ON COLUMN user_event.occurred_at IS
    '★ 客户端报的时间。时间窗口口径按它切。与 received_at 的差 = 时钟偏差 + 网络延迟，'
    '两者在数据上分不开 —— 所以要两列都留。';

COMMENT ON COLUMN user_event.received_at IS
    '★ 服务端收到的时间（本表的 created_at，改名是为了承担对比语义）。';

CREATE UNIQUE INDEX uk_user_event_no ON user_event (event_no);
CREATE INDEX idx_user_event_type_time ON user_event (event_type, occurred_at DESC);
CREATE INDEX idx_user_event_trace ON user_event (trace_id);
