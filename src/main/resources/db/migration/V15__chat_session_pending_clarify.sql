-- ============================================================
-- V15 · chat_session 加 pending_clarify（阶段 9.4 · 多轮澄清 / 槽位填充）
--
-- ⚠️ V1~V14 一个字都不能改 —— `validate-on-migrate: true` 会让应用起不来。
--    所以这里只做 ALTER。
--
-- 一件事：pending_clarify JSONB ——
--   「上一轮我们（助手）问过什么、还没拿到回答」的那点状态。
-- ============================================================


-- ============================================================
-- 一、它解决的是什么问题
-- ============================================================
--
-- 澄清反问（5.3）到今天为止是【单轮、无状态】的：ClarificationDecider
-- 只看分类落点是不是 role: CLARIFY 那个分支（NEEDS_CLARIFICATION），
-- 命中就短路（不检索、不调生成），回一句固定的反问文案。
--
-- 而分类器的输入【只有这一句话】（ADR-046 的决策，5.2 的准确率和
-- 5.4 的「20/20 可证明安全」都建立在它之上）。于是：
--
--   用户：那个怎么样        → 澄清「你是想问哪款商品呢？」
--   用户：送长辈            → 分类器只看到「送长辈」三个字
--                          → 仍然是「信息不足」→ 【再问一次】
--
-- ★ 这不是猜想，是实测：docs/05 §9.5 ② 记着
--   「最自然的追问方式有约 2/3 的概率被澄清闸门挡掉」
--   （三次运行的结果：澄清 / 放行 / 澄清）。
--
-- 这一列存的就是「上一轮问了什么」，让【紧接着的那一轮】分类时看得见它。
-- ★★ 注意它【不是】会话历史：历史是自由文本、每轮都会喂（那是 5.5 的机制，
--    只给生成）；这里是一小段结构化状态、只出现一轮、只进分类。


-- ============================================================
-- 二、★★ 为什么不从 qa_log 反推
-- ============================================================
--
-- 「上一轮缺哪些槽位」确实已经在库里了 —— 澄清行照样写 qa_log.intent_plan，
-- 里面的 missing 就是槽位（9.2 起就在产，只是没有消费方）。
-- 那为什么不 JOIN 出来用？
--
--   ① 反推要回答「同一会话里，上一行是哪一行」——那是一个带排序的窗口问题，
--      而 qa_log 的写入时机分散在 5 个落库方法里（成功/失败/流式/工具/澄清）。
--   ② 更要紧的是【它答的不是同一个问题】：
--      库里的 missing 是「上一轮缺什么」，而这里要的是
--      「这一轮还要不要接着上一轮问」——后者是【状态】，不是【历史事实】。
--      状态有它自己的生命周期（写入 / 消费 / 清空），而历史事实没有。
--   ③ 反推在数据上也不可靠：排队被拒的行（status=4）不进 ChatService，
--      夹在中间会让「上一行是不是澄清」判错，而那个错【没有任何迹象】。
--
-- ⇒ 状态就是状态，让它有一个明确的家。


-- ============================================================
-- 三、★ 为什么是一列，而不是一张新表
-- ============================================================
--
-- 它和会话是【一对一】且【同时消亡】的：一个会话最多有一份待澄清状态。
-- 建一张表要多一个 JOIN、多一套生命周期（谁清、什么时候清），
-- 而它要回答的问题只有一个：「这个会话有没有悬着的反问」。
--
-- ★ 也不要塞进 chat_session 现有的任何一列：
--   title 是首轮问题、status 是 1进行中/2已结束（而且它有 CHECK 约束，
--   借它表达「待澄清」要拆约束 + 迁移语义，见 V7 拆 ck_qa_log_status 的代价）。
--   ★★ 排除 title 那条尤其重要：它是 write-once 的，覆盖它会让会话列表
--      显示的是「最后一个用户回答」而不是「这个会话在聊什么」。


-- ============================================================
-- 四、★ 为什么「没有待澄清」写 NULL，而不是 '{}'
-- ============================================================
--
-- 同 tool_calls / retrieval_detail / references / intent_plan 那条
-- 贯穿全库的约定：「没有发生」和「发生了但是空的」必须能区分开。
--
-- 在这里，那两者分别是：
--   没有待澄清            → NULL       （这次问答和前一轮没关系）
--   有待澄清但槽位是空的   → '{"slots":[]}'  ← 合法但罕见：我们问了，却不知道问的是什么
--
-- ★ 把前者写成 '{}' 的代价：分析时它会被算成「有一次待澄清」，
--   于是「澄清恢复率」这个指标的分母里混进一堆从没问过反派的轮次 ——
--   而它看起来只是一个偏低的百分比，不会报错。


-- ============================================================
-- 五、★★ 生命周期：读后即清（不需要 TTL 字段）
-- ============================================================
--
--   澄清轮结束   → 写：{原问题, 缺的槽位, 问了哪个槽, 时间}
--   下一轮开始   → 【读出来，并立刻清空】→ 之后无论这一轮怎么走都不再管它
--
-- ★ 「立刻清空」是关键：它让这一列是【一次性】的，
--   于是不存在「一个坏状态永久卡住那个会话」那种形态
--   （ADR-049 的孤儿消息就是那个形态：连续两次失败后会话永久答不出话）。
--   ⇒ 因此这一列【不需要】过期时间字段，也【不需要】定时清理任务。
--
-- ⚠️ 已知的、刻意接受的代价：用户如果【换了话题】，那句注入仍然会进
--    下一轮的分类 prompt（我们无法在分类之前知道他要换话题）。
--    缓解有两层，都在代码里：① 用一次即清，窗口只有一轮；
--    ② prompt 里的措辞写成「如果这句话是在回答上一个问题…否则忽略它」，
--    把判断权交给模型。记在 docs/05 §9.10 的已知问题里。


-- ============================================================
-- 六、加不加索引 —— 不加
-- ============================================================
--
-- 没有任何查询要按这一列过滤或排序：它只在「拿到会话行之后」被读一次，
-- 而那次读走的是主键。同 V8 给 tool_calls、V14 给 intent_plan 的决定 ——
-- 分析用的列，让分析的时候慢一点，不要在写入路径上一直付钱。
--
-- ★ 也【不】给它加 GIN 索引：V13 已经记过一次
--   「JSONB 的 GIN 索引对写入有实打实的代价」。


-- ============================================================
-- 七、改动
-- ============================================================

ALTER TABLE chat_session ADD COLUMN IF NOT EXISTS pending_clarify JSONB;

COMMENT ON COLUMN chat_session.pending_clarify IS
    '悬着的澄清反问状态（阶段 9.4）。形状：'
    '{"v":1,"question":"那个怎么样","slots":["product"],"asked":"product","at":"...ISO..."}。'
    '★ NULL = 没有待澄清（常态），不是空对象 —— 同 tool_calls / intent_plan 的约定。'
    '★★ 生命周期是【读后即清】：澄清轮写入，紧接着的下一轮读出来并立刻清空。'
    '一次性，所以没有 TTL 字段、也不需要定时清理（不存在永久卡住的形态）。'
    '★ 它只在【分类那一次调用】里被用（拼进 prompt 的结构化状态），'
    '不进生成 prompt、不进检索 —— 那是 ADR-046「历史只给生成」的边界：'
    '禁的是自由文本历史，而这是一小段结构化状态、且只出现一轮。';
