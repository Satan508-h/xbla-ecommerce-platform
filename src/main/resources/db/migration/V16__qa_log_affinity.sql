-- ============================================================
-- V16 · qa_log 加 affinity（阶段 9.5 · 个性化）
--
-- ⚠️ V1~V15 一个字都不能改 —— `validate-on-migrate: true` 会让应用起不来。
--    所以这里只做 ALTER。
--
-- 一件事：
--   affinity TEXT   —— 这一次问答拼进 system prompt 的【偏好块原文】
-- ============================================================


-- ============================================================
-- 一、为什么是【文本】而不是 JSON
-- ============================================================
--
-- 同阶段的其它列（intent_plan / tool_calls / retrieval_detail）都是 JSONB，
-- 因为它们是给【程序】读的结构化中间结果。这一列不是 ——
-- 它的全部用途是两件事：
--
--   ① 「偏好块到底进没进 prompt」有一个能查的判据
--   ② 评测要把它【逐字】还给 RAGAS 当上下文（见下）
--
-- 而这两件事要的都是「模型当时看到的那几个字」。
-- 存 JSON 再在读取端重新渲染一遍，就多出一个「渲染漂移」的机会 ——
-- 那正是 ADR-058 与 RagPromptBuilder.factsSection 那条「只写一次」的纪律。
--
-- ★ 所以它存的与拼进 prompt 的是【同一段字符串】，中间没有任何再加工。
--
--
-- ============================================================
-- 二、★★★ 为什么必须快照，而不能像硬数据那样重建
-- ============================================================
--
-- 阶段 5.9 的硬数据（售后政策天数）在评测里是【无参重建】的：
--   EvalAnswerService → PolicyFactProvider.load() → RagPromptBuilder.factsSection
-- 敢这么做的前提是它是【无参纯读】：同一份库必然产出逐字相同的一段。
--
-- 偏好块【不满足】那个前提，而且是两重不满足：
--
--   ① 它是 per-user 的 —— 重建必须知道「这一行是谁问的」，
--      而那是 qa_log.user_id，一个从阶段 9 起才真的有值的列
--      （它甚至是【两张形状表】的叠加：9 之前的行恒 NULL、
--        头缺席 NULL、头指向不存在的人则原样记着那个值）
--   ② 它随订单【变】—— 「当时的偏好」和「现在的偏好」是两回事。
--      评测跑在提问之后（实测：RAGAS 一轮约 2 小时/43 题），
--      期间任何一笔新订单都会让重建出来的段落当时的不是同一个东西
--
-- ★★ 不快照的后果是【静默】的：报告里的 faithfulness 偏低，
--    而看报告的人会去调一个根本没坏的东西（同 factsSection 那条警告）。
--
-- ★ 代价是这一列会随每一条 qa_log 写一段几百字的文本。
--   接受它：qa_log 已经是全库最宽的表，而这几百字换来的是
--   「模型当时看到了什么」这个唯一能在事后回答的答案。
--
--
-- ============================================================
-- 三、为什么 NULL 而不是空串
-- ============================================================
--
-- 同 intent_plan / tool_calls / retrieval_detail / references 那条贯穿全库的约定：
--   【「没发生」和「发生了但是空的」必须能区分开】
--
-- 这里的「没发生」有四种，而且它们【都是正常状态】：
--
--   匿名提问（没有 X-Xbla-User-Id）           —— 没有「谁」可以个性化
--   身份指向一个 app_user 里不存在的人（999999）—— 同上，且工具那条路也一样
--   有身份，但有效订单不足 min-orders（实测 30 人里 10 人）—— 证据不够
--   开关关掉（xbla.agent.profile.enabled=false）—— 就是 9.4 的样子
--
-- ★ 判据：`WHERE affinity IS NOT NULL` 筛出的是「这一次真的注入了偏好块」。
--   写成 '' 的话这个筛子会把上面四种全部算进去。
--   而「偏好一次都没注入」这件事在数据上本来完全看不出来 ——
--   正是这一列要防的（同 9.2 的 intent_plan.shape）。
--
--
-- ============================================================
-- 四、加不加索引 —— 不加
-- ============================================================
--
-- 同 V8 / V14 的决定：qa_log 是写入最频繁的表，而这一列只在
-- 【分析 + 评测】路径上被读到，且是整行读（不做 LIKE 筛选）。
-- 分析用的列，让分析的时候慢一点，不要在写入路径上一直付钱。
-- ============================================================

ALTER TABLE qa_log
    ADD COLUMN IF NOT EXISTS affinity TEXT;

COMMENT ON COLUMN qa_log.affinity IS
    '偏好块原文（阶段 9.5）：这一次拼进 system prompt 的那几百字，与 prompt 里逐字相同。'
    'NULL = 这次没有注入（匿名 / 身份不存在 / 有效订单不足 min-orders / 开关关掉），不是空串。'
    '★★ 它是【快照】而不是重建：偏好 per-user 且随订单变，评测无法像硬数据那样无参重建，'
    '不快照会让报告里的 faithfulness 静默偏低。';
