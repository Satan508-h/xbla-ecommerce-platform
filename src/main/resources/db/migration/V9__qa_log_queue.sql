-- ============================================================
-- 一、为什么需要 queue_ms
-- ============================================================
--
-- 阶段 6 之前，「用户等了多久」这个问题只有一个答案：total_latency_ms。
-- 而它从阶段 6 起变成了**两个数的和**：
--
--     total_latency_ms = queue_ms + （检索 + 重排 + 生成）
--                        └─ 排队 ─┘   └─ 我们真正在干活的部分 ─┘
--
-- 合成一个数之后就再也拆不开了，而这两段的优化方向完全相反：
--
--     排队时间长  →  并发上限太小 / 下游太慢 / 流量真的超了
--     干活时间长  →  检索慢、重排慢、模型慢 —— 阶段 4/7 一直在治的那个
--
-- ★ 而且这是**唯一会消失的数据**：Redis 里的队列状态是运行时的，
--   名额一释放、进程一重启就没了。不落库就永久丢失。
--   （同 V5 里 retrieval_detail 的理由：过程信息不记下来，
--   事后只能靠复现去猜。）
--
-- ⚠️ 排队的**花费不进成本统计**：排队期不调模型，队列本身也不花钱。
--   这一点和「摘要压缩的花费不进 qa_log」是同一条边界
--   （见 CLAUDE.md 里那条约定的说明）。


-- ============================================================
-- 二、为什么需要 queue_position —— 以及它必须是【入队时】的位置
-- ============================================================
--
-- queue_ms 只说明「等了多久」，不说明「当时有多挤」。
-- 同样是等 30 秒：
--
--     前面 1 个人，每个人跑 30 秒   →  下游慢
--     前面 50 个人，每个人跑 0.6 秒 →  并发上限太小
--
-- 后者的修法是调大 permits，前者是去查模型/检索。**没有这一列区分不了。**
--
-- ★★ 但它必须记「**刚入队时**的位置」，不能记「被授予时的位置」——
--    因为**后者恒为 0**。
--
--     被授予的那一刻，你必然是队首（不然轮不到你）。
--     所以记「最终位置」会得到一整列 0：
--     它看起来是数据、有类型、有值，**但它不携带任何信息** ——
--     而这比 NULL 危险得多，因为它不像缺失，像是「所有人都没排队」。
--
-- ⚠️ 它是「前面还有几个人」（0-based，和 ZRANK 的原生语义一致），
--    不是「我是第几个」。第一个人这一列是 0。
--    转化成人话给用户看时是「你前面还有 0 位」—— 恰好不用 +1。


-- ============================================================
-- 三、NULL 与 0 的分工（沿用本表既有的约定）
-- ============================================================
--
--     NULL  = 这件事**没有发生**
--     值    = 发生了，这是它的数字
--
--   queue_ms = NULL        → 没排队（名额有空，直接进来了）
--   queue_position = NULL  → 没进过队列
--   queue_position = 0     → 进过队列，而且是队首
--
-- ★ 关键：**不能把「没排队」记成 0**。
--   阶段 7 要回答「排队限流开了之后，平均多等多久」——
--   把「没排队」算成 0 会把平均值往下拉，
--   而且「没开排队」和「开了但没排队」在数据上会变得一模一样。
--   （同 ADR-010「拿不到就记 NULL」、以及 rewritten_question
--   在开关关闭时存 null 而不是存原文。）
--
-- ⚠️ xbla.ratelimit.enabled=false 时，这两列**也是 NULL** ——
--    不是 0。见 RateLimitProperties#enabled 的注释。


-- ============================================================
-- 四、为什么要第四个 status（=4 被限流）
-- ============================================================
--
-- 阶段 6 之前，每一个到达 /api/chat 的请求都会产生一行 qa_log。
-- 阶段 6 打破了这一点：**被拒绝和排队超时的请求根本没进 ChatService**，
-- 所以它们一行都不写。
--
-- 后果是数据上出现一个**结构性的盲区，而且它随负载变大而变大**：
--
--     100 个人来问，8 个在跑、92 个排队
--       → 其中 30 个最终被拒或超时
--       → qa_log 里只有 70 行
--       → 而那 30 个在**任何地方都没有记录**
--
-- ★ 这个方向是反的：**越忙越需要数据**，而恰恰越忙丢得越多。
--   而且「随机失败率」在前端看来是用户体验的核心指标，
--   阶段 7 却完全看不到它。
--
-- 为什么不复用 status=2（模型链路失败）：
--
--   2 说的是「模型挂了」，4 说的是「我们没让它进来」。
--   前者去查降级链和供应商，后者去调 permits / max-queue / 下游速度。
--   **两种修法完全相反，而共用一个值会让它们在数据上长得一样** ——
--   这正是 V7 里澄清反问那段写过的同一类错误。
--
-- ★ 4 内部还分两种（队列满 vs 排队超时），用已有的 error_msg 区分，
--   不为此再加一个值 —— 它们的方向是一致的（容量不够），
--   而且 error_msg 本来就是本表记录失败细节的地方（status=2 也用它）。
--
-- ★ 这一类行的形状：question / trace_id / queue_ms / queue_position 有值，
--   provider / model / tokens / cost / final_answer 全为 NULL ——
--   和 status=3（澄清反问）的行形状一致：**没有发生的事就留空**，
--   不填空对象、不填 0。
--
-- ⚠️ CLAUDE.md 那条「评测指标只统计 status = 1」**不受影响**：
--   新值不参与任何指标，反而让「被限流掉的比例」第一次可以被算出来。


-- ============================================================
-- 五、为什么不加索引
-- ============================================================
--
-- 和 V8 加 tool_calls 时同一个决定：qa_log 是写入最频繁的表，
-- 而这两列只用于事后分析，不在任何在线路径上。
--
-- ★ 顺带说明一个本表**没有**的东西：qa_log 上目前没有任何索引，
--   连 created_at 都没有。阶段 7 跑一次全表扫描几百毫秒，可以接受；
--   真到了需要的时候，先做**按时间分区**（收益比索引大得多），
--   而不是逐列加索引。
-- ============================================================


-- ============================================================
-- 一、两列
-- ============================================================

ALTER TABLE qa_log ADD COLUMN queue_ms INT;

COMMENT ON COLUMN qa_log.queue_ms IS
    '★ 排队等待毫秒数。NULL = 没排队（名额有空，直接进来的），不是 0。'
    '★ total_latency_ms 从阶段 6 起包含它 —— 两者的差才是「真正在干活」的耗时。'
    '排队期不调模型，所以它不计入 cost。';

ALTER TABLE qa_log ADD COLUMN queue_position INT;

COMMENT ON COLUMN qa_log.queue_position IS
    '★ 刚入队时「前面还有几个人」（0-based，队首是 0）。NULL = 没进过队列。'
    '⚠️ 必须在【入队那一刻】取，不能在拿到名额时取 —— 后者恒为 0，'
    '一整列 0 看起来像数据，实际上不携带任何信息。';


-- ============================================================
-- 二、status 扩到 4
-- ============================================================

ALTER TABLE qa_log DROP CONSTRAINT ck_qa_log_status;

ALTER TABLE qa_log ADD CONSTRAINT ck_qa_log_status CHECK (status IN (1, 2, 3, 4));

COMMENT ON COLUMN qa_log.status IS
    '1成功生成答案 2模型链路失败 3澄清反问（未生成答案，也未失败）'
    '4被排队限流拒绝或排队超时（根本没进问答链路）';

-- ★ 阶段 7 的检索类与答案质量类指标仍然【只统计 status = 1】：
--     2 根本没有答案、3 没有答案可评（那是句反问）、4 连链路都没进。
--
-- ⚠️ 同 V7 的说明：不建 `WHERE status = 1` 的视图 ——
--    SELECT * 的视图会在以后加列时静默变陈旧。
--    取值定义在 Java 侧：QaLog.STATUS_SUCCESS / STATUS_FAILED /
--    STATUS_CLARIFY / STATUS_RATE_LIMITED，代码里不出现裸数字。
