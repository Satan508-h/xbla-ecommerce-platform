-- V10 · qa_log 增加评测运行标记（阶段 7 评测体系）
--
-- ⚠️ V1~V9 一个字都不能改 —— `validate-on-migrate: true` 会让应用起不来。
--    所以这里只做 ALTER，不回头改 V5。
--
-- 两列：eval_run_id / eval_question_no。都可空，且 **NULL 是常态**。
-- 不建索引（理由见第四节，沿用 V9 那条结论）。
-- ============================================================


-- ============================================================
-- 一、为什么需要它 —— 阶段 7 会往这张表里灌「假用户」
-- ============================================================
--
-- 阶段 4 的基线脚本**根本不写库**（它只调检索探针，见 eval_baseline.py 的注释），
-- 所以那时没有这个问题。阶段 7 不一样：答案质量指标（RAGAS 四指标）
-- 需要**真实生成的答案**，而唯一能产出它的是 `/api/chat` —— 于是评测
-- 会把 150 题 × 重复次数 的记录写进 chat_session / chat_message / qa_log。
--
-- 为什么**必须**走真实链路、而不是另起一条「只跑 RAG 的评测旁路」：
--
--     旁路跑出来的指标描述的是那条旁路，不是用户走的路。
--     两条路会漂移，而漂移是静默的 —— 这正是 ADR-045
--     （调试接口和落库调同一个纯函数）要防的同一类错误。
--
-- ★★ 代价是：**评测流量与真实使用流量混在同一张表里**。
--    没有标记的话，事后完全无法分离 —— 而「分不开」这件事没有任何症状，
--    只会让「真实用户平均等多久 / 真实召回率多少」被 450 条评测记录主导。
--
--    ⚠️ 这个盲区会随时间**自动变大**：每跑一轮评测就多几百行，
--       而真实使用的量取决于有没有人来用。最坏情况是评测数据把真实数据淹没。


-- ============================================================
-- 二、为什么是「加列」，而不是那三种更省事的做法
-- ============================================================
--
-- ① 往 question 里加前缀（"[评测] 退货要几天"）
--    ✗ 题面是**检索的输入**：加了前缀，向量和关键词都要拿它去搜，
--      召回结果就不是真实题面该有的结果了。
--    ✗ 而分类器也要读这句话 —— 它会开始把「评测」当成业务词。
--
-- ② 靠 trace_id 事后回填（跑完拿响应里的 traceId 批量 UPDATE）
--    ✗ 回填是一次**独立的写操作**，它会失败（进程崩了、网络断了、脚本被 Ctrl-C）。
--      失败之后的那些行：既不在评测统计里（没有标记），
--      又混在真实数据里（有标记的话本来可以排除）——**两头都不属于**，且无症状。
--
-- ③ 另开一张 qa_log_eval 表
--    ✗ 写入路径要分叉（`baseLog` 得判断往哪张表写），
--      而分叉的两条路会漂移；更要紧的是，那样评测的**排队/降级/成本**
--      就只能在另一张表里统计了 —— 而它们本该是同一批数据。
--    ✓ 但它有一个真实的好处：**物理上不可能漏掉过滤条件**（见第五节）。
--      权衡之后没选：本项目的做法是「一个概念一列 + 文档纪律」，
--      和 `status = 1` 那条是同一个形态。
--
-- ④ 用 user_id 区分
--    ✗ 走不通：`chat_session.user_id` 在 chat 路径上**恒为 NULL**
--      （见 ChatServiceImpl.resolveSession）。而且真实用户也可能有 id。


-- ============================================================
-- 三、为什么是【两列】而不是一列
-- ============================================================
--
--     eval_run_id      哪一轮评测
--     eval_question_no 那一轮里的哪一题
--
-- 只存 run_id 的话，报告就没法把 qa_log 的行**对上题目**
-- （要算意图准确率就得知道这行是回答哪个问题的、它的 gold 是什么）。
-- 那时的做法只能是拿 `qa_log.question = eval_question.question` 去 JOIN ——
--
--     ★ 而这是一个**静默错误**：真实用户恰好问了同一个问题时，
--       那一行也会被算进评测统计。不报错，只是数字偏了。
--
-- ⚠️ 两列**必须一起出现**：有 run_id 没有 question_no 的行无法归题，
--    等于白标；有 question_no 没有 run_id 则无从知道是哪一轮。
--    （不建 CHECK 约束强制它们同生共死 —— 那会让「手工插入一条只有 run_id 的
--     行」变成数据库级报错，而调试期这种行是有用的。但报告端点里要能看见它们。）


-- ============================================================
-- 四、为什么不加索引
-- ============================================================
--
-- 沿用 V9 的结论，不逐列加索引：qa_log 是写入最频繁的表，
-- 而这两列只用于事后分析，不在任何在线路径上。
-- 报告端点一次扫全表（当前量级几百行）是毫秒级。
--
-- 真到了需要的时候，先做**按时间分区**（收益比索引大得多）。
-- ★ 如果哪天确实要加，正确的形态是**部分索引**：
--     CREATE INDEX ... ON qa_log (eval_run_id) WHERE eval_run_id IS NOT NULL;
--   因为绝大多数行的这两列是 NULL（真实用户），全量索引里那些 NULL 是纯负担。


-- ============================================================
-- 五、★ 由此产生的两条查询纪律（写在这里，因为列在这里）
-- ============================================================
--
--   统计【真实使用】→  WHERE eval_run_id IS NULL
--   统计【某轮评测】→  WHERE eval_run_id = '...'   （且按 question_no 归题）
--
-- ⚠️ 两条都不加 = 数字被评测数据主导，而且**看不出来**。
--   这和 `status = 1` 那条纪律是同一个形态：一个必须每处都记得的条件。
--   之所以还是选了加列而不是另开表，是因为它至少**可查**——
--   `SELECT eval_run_id, count(*) FROM qa_log GROUP BY 1` 一眼就能看出
--   表里有多少评测数据；另开表则连这张表里混没混东西都看不出来。
-- ============================================================


-- ============================================================
-- 六、两列
-- ============================================================

ALTER TABLE qa_log ADD COLUMN eval_run_id VARCHAR(64);

COMMENT ON COLUMN qa_log.eval_run_id IS
    '评测运行 ID（阶段 7）。★ NULL = 真实用户的提问，不是评测数据 —— 是常态。'
    '★ 统计真实使用必须加 WHERE eval_run_id IS NULL，否则数字被评测数据主导。'
    '★ 反过来，它让「这一轮的排队/降级/成本/召回」第一次可以整体复算。';

ALTER TABLE qa_log ADD COLUMN eval_question_no VARCHAR(32);

COMMENT ON COLUMN qa_log.eval_question_no IS
    '该轮评测里的题号，对应 eval_question.question_no（阶段 7）。NULL = 同上。'
    '⚠️ 它必须存在，不能靠 qa_log.question = eval_question.question 去 JOIN —— '
    '真实用户问了同一个问题时，那一行会被静默算进评测统计。';

-- ★ 本迁移**不动 status 的 CHECK 约束**（仍是 (1,2,3,4)）：
--   评测行同样是这四种状态之一，不需要第五种。
--   「这一行是评测」和「这一次问答成功没有」是两个正交的维度，
--   塞进同一个列会让两者都变得不可解释（同 V7 把「澄清」放进 status 的理由，
--   方向相反但道理一样：一个维度只承载一类信息）。
