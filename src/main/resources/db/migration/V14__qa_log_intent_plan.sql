-- ============================================================
-- V14 · qa_log 加 intent_plan（阶段 9.2 · Agentic RAG 的检索门控）
--
-- ⚠️ V1~V13 一个字都不能改 —— `validate-on-migrate: true` 会让应用起不来。
--    所以这里只做 ALTER。
--
-- 一件事：
--   intent_plan JSONB   —— 意图分类那一次调用顺带产出的【结构化计划】
-- ============================================================


-- ============================================================
-- 一、为什么需要它 —— 「决定不检索」这件事没有地方记
-- ============================================================
--
-- 阶段 9.2 让意图分类的输出从一个叶子码扩成一个计划：
--
--   {"v":1,"intent":"SPEC_QUERY","retrieve":true,"gate":"KB","missing":[],"shape":"JSON"}
--
-- 两个新事实需要落库：
--   retrieve  这次到底该不该检索（模型说的 + 意图树声明的，取交集后的结论）
--   shape     模型有没有按新契约作答（写的是 JSON 还是只回了裸码）
--
--
-- ============================================================
-- 二、★★ 为什么不塞进 retrieval_detail —— 那个决定是刻意的
-- ============================================================
--
-- ADR-082 定过一条纪律：`retrieval_detail` 的扩展一律是【加法式】的
-- （只加键，不改已有键的形状）。按那条纪律，这里本来是可以塞进去的。
--
-- 但有一条否决理由，而且是决定性的：
--
--     ★ retrieval_detail 在【没有检索】的时候是 NULL ★
--
-- 而「决定不检索」恰恰是本阶段最需要记录的那一刻 ——
-- 塞进去等于在【最需要它的那条路上】把它丢掉：
--
--   模型说「这句不用检索」 → 检索没跑 → retrieval_detail = NULL
--   → 那个「不用检索」的决定跟着一起没了
--   → 事后无法回答「门控到底关掉过几次检索」
--
-- 同 ADR-041 那条「没有发生就说没有发生」的另一个侧面：
-- 那一条讲的是「不要把没发生写成空对象」，
-- 这一条讲的是「不要把新信息存进一个在没发生时必然为 NULL 的列里」。
--
--
-- ============================================================
-- 三、★★★ shape 是这一列里最重要的一格
-- ============================================================
--
-- 没有它，9.2 最可能发生的失败是【完全静默】的：
--
--   prompt 改成了「输出 JSON」，但模型照旧只吐一个裸 code
--   → 解析器走回退路径 → 分类照样成功、问答照样回答
--   → 而【门控一次都没生效过】
--   → 报告上所有旧指标一格不动，没有任何东西会红
--
-- shape 的分布一印出来，这件事当场可见：
--   JSON      模型按新契约答的
--   CODE      只回了一个裸码（老契约）—— 能跑，但拿不到计划
--   UNPARSED  两种都不是 → 分类整体失败
--
-- ★ 判据：JSON 占比应该接近 100%。掉下来就说明模型没跟上契约，
--   那时候「门控有没有用」这个问题根本无从谈起。
--
--
-- ============================================================
-- 四、为什么 NULL 而不是 '{}'
-- ============================================================
--
-- 同 tool_calls / retrieval_detail / references 那条贯穿全库的约定：
--   【「没发生」和「发生了但是空的」必须能区分开】
--
-- 这里的「没发生」= 这次分类没有产出计划：分类整个失败，
-- 或者是测试直接构造的结果（那些点位没有模拟计划）。
--
-- ★ 所以 `WHERE intent_plan IS NOT NULL` 是一个有意义的筛子：
--   它筛出的是「这一次真的走完了分类并拿到了计划」的那些行。
--
--
-- ============================================================
-- 五、加不加索引 —— 不加
-- ============================================================
--
-- 同 V8 给 tool_calls 的决定：qa_log 是写入最频繁的表，
-- 而这一列只在【分析路径】上。分析用的列，让分析的时候慢一点，
-- 不要在写入路径上一直付钱。
--
-- ★ 真要按 retrieve 筛的时候，用 GIN 或表达式索引都来得及 ——
--   那是一个可以后补的决定，而写入成本是每一条都要付的。
-- ============================================================

ALTER TABLE qa_log
    ADD COLUMN IF NOT EXISTS intent_plan JSONB;

COMMENT ON COLUMN qa_log.intent_plan IS
    '结构化计划（阶段 9.2）：{v,intent,retrieve,gate,missing,shape}。'
    'NULL = 这次分类没有产出计划（分类失败，或测试构造的结果），不是空对象。'
    '★★ shape 记录「模型有没有按新契约作答」—— 它是「门控有没有生效」的唯一判据。'
    '★ 它不塞进 retrieval_detail 的理由是：那一列在【没有检索】时是 NULL，'
    '而「决定不检索」正是最需要记录的时刻。';
