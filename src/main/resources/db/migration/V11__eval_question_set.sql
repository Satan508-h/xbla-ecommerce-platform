-- ============================================================
-- V11 · eval_question 用 question_set 取代 is_baseline（阶段 7 评测体系）
--
-- ⚠️ V1~V10 一个字都不能改 —— `validate-on-migrate: true` 会让应用起不来。
--    所以这里只做 ALTER。
--
-- 两件事：
--   ① 加 question_set VARCHAR(32) NOT NULL（无 DEFAULT，见第三节）
--   ② 删 is_baseline 和它的部分索引
-- ============================================================


-- ============================================================
-- 一、为什么需要 question_set —— 阶段 7 有【三套】题
-- ============================================================
--
-- 阶段 4 之后只有一套题（20 道反向构造的基线）。阶段 7 变成三套，
-- 而它们的**口径完全不同**，混在一起算指标会得到一个不描述任何东西的数：
--
--   baseline      20 题   反向构造，单轮。阶段 4 的基线，保留用于纵向对比
--   stage7        ~150 题 读语料手写，单轮。7.1 的主体
--   stage7-multi  ~20 题  多轮追问。★ 判据和上面两套【不同类】——
--                         追问轮的正确答案依赖上下文，不能和单轮混算
--
-- ★ 所以「这次跑的是哪一套」必须是数据里的一个字段，
--   而不是「你记得自己刚才 reload 了哪个文件」。
--   报告里每一张表都要写清它统计的是哪一套 —— 这是「每个数字能解释怎么来的」的一半。
--
-- ⚠️ 三套题**共用**同一张表：它们的形状完全一样（题面/意图/gold/锚点），
--   只是口径不同。分表会让「读全部题」这种查询变成 UNION，
--   而那个 UNION 每加一套题就要改一次。


-- ============================================================
-- 二、为什么删 is_baseline —— 一个概念只能有一列
-- ============================================================
--
-- is_baseline 是 V5 加的（BOOLEAN NOT NULL DEFAULT false），语义是
-- 「是否纳入基线评测集，用于 A/B 对比」。它现在有三个问题：
--
--   ① ★ 它**恒为 true**。20 行全是 true —— 一个只有一个取值的列不携带信息。
--      它唯一的作用是区分「题」和「别的什么」，而这张表里只有题。
--
--   ② ★ boolean 表达不了三套题。第二套题来了，它只能继续写 true，
--      于是「baseline」这个名字开始撒谎。★ 而**名字撒谎的列比没有列更糟**：
--      后来的人会按名字理解它，而名字是唯一没有跟着变的东西。
--
--   ③ ★ 两个列描述同一件事（「这题属于哪套」）时，它们**可以互相矛盾**。
--      矛盾了不会报错，只会让某个查询悄悄多算/少算一批题。
--      同 ADR-057「一个名字只写一次」、RedisQueueKeys「key 名只能写一次」——
--      **两处各写一份的漂移是静默的**。
--
-- ★ 为什么不能只加 question_set 而把 is_baseline 留着不用：
--   那正是 CLAUDE.md 里被点名的债（chat_summary.summary_level 恒为 1、
--   token_count 恒为 NULL）。留一个「有列不用」的字段，
--   下一个人会去猜它是不是还有用、要不要一起写。
--   ★ 删列不丢信息：那 20 行 = question_set 'baseline'，一一对应。
--
-- ⚠️ V1~V9 不能改 ≠ 不能删它们加的东西。删要通过**新的**迁移，
--   也就是这里。V5 那份历史记录仍然是完整的（它当时确实建了 is_baseline）。


-- ============================================================
-- 三、为什么 question_set 不加 DEFAULT
-- ============================================================
--
-- 有 DEFAULT 的话，「忘了写 question_set」会被静默填成那个默认值 ——
-- 于是一道新题的出身变成了一个**从来没人断言过**的值。
--
-- 无 DEFAULT + NOT NULL 的话，漏写会直接 INSERT 失败。
-- 而加载器（EvalQuestionLoader）无论如何都会写它（文件顶层必填），
-- 所以这条约束在正常路径上永远不会被触发 ——
-- **它只在有人手写 SQL 插入时才生效，而那正是需要被拦住的场景**。
--
-- ★ 三步走（加可空 → 回填 → 设 NOT NULL）而不是「加 NOT NULL DEFAULT」：
--   后者会给已有行也打上一个默认值，而那 20 行的真实出身是 'baseline'，
--   只是它恰好和默认值相同 —— 巧合不是证据。
-- ============================================================


-- ============================================================
-- 四、改动
-- ============================================================

ALTER TABLE eval_question ADD COLUMN question_set VARCHAR(32);

-- 回填：这一列加进来之前，表里只可能是阶段 4 的那一套题
UPDATE eval_question SET question_set = 'baseline' WHERE question_set IS NULL;

ALTER TABLE eval_question ALTER COLUMN question_set SET NOT NULL;

COMMENT ON COLUMN eval_question.question_set IS
    '这道题属于哪一套题集（阶段 7）。'
    'baseline=阶段4的20道反向构造题 / stage7=阶段7的150道单轮题 / '
    'stage7-multi=阶段7的多轮追问题。'
    '★★ 三套题的口径不同，【不能混在一起算指标】—— 报告里每张表都要写清是哪一套。'
    '⚠️ 无 DEFAULT：漏写会 INSERT 失败，而不是被静默填成 baseline。';

DROP INDEX idx_eval_question_baseline;

ALTER TABLE eval_question DROP COLUMN is_baseline;

-- ★ 不加 question_set 的索引：三套题一共不到 200 行，
--   而这张表只在 reload 和报告端点被扫。同 V9「qa_log 不加索引」的理由。
