package com.xbla.rag.config;

import lombok.Data;
import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * 知识库（文档入库）相关配置，对应 {@code application.yml} 里的 {@code xbla.kb}。
 *
 * <p><b>为什么这些参数要放配置文件而不是写死在代码里</b>：
 * 阶段 7 要做 A/B 对比调优，而<b>切分粒度是首当其冲要调的参数</b> ——
 * 切片太长会引入无关噪声，太短会丢上下文。
 * 如果写死在代码里，每调一次都要改代码 + 重新编译 + 重新打包；
 * 放配置里，改一行 YAML 重启即可。
 *
 * <p>命名上区分两类：
 * <ul>
 *   <li><b>路径类</b>（{@code storageDir} / {@code corpusDir}）：指向文件系统</li>
 *   <li><b>算法类</b>（嵌套的 {@code Chunking} / {@code Embedding}）：控制行为</li>
 * </ul>
 */
@Data
@ConfigurationProperties(prefix = "xbla.kb")
public class KbProperties {

    /**
     * 上传文件的落盘根目录。<b>相对于应用启动目录</b>。
     *
     * <p>落在 {@code data/uploads/} 而不是 {@code data/corpus/}：
     * 前者是用户上传的原始文件，后者是我们自己生成的仿真语料，两者用途不同，
     * 混在一起会让「清理测试数据」变成一件危险的事。
     *
     * <p>⚠️ 这个目录已在 {@code .gitignore} 里。上传的文件<b>不进 git</b> ——
     * 体积大、可重新上传，而且可能是用户的隐私数据。
     */
    private String storageDir = "data/uploads";

    /**
     * 仿真语料目录（{@code scripts/generate_corpus.py} 的输出位置）。
     *
     * <p>目录扫描接口会从这里读文件批量入库。
     */
    private String corpusDir = "data/corpus";

    /** 切分参数 */
    private Chunking chunking = new Chunking();

    /** 向量化参数 */
    private Embedding embedding = new Embedding();

    /** 入库线程池参数 */
    private Ingest ingest = new Ingest();

    // ================================================================
    // 切分
    // ================================================================

    @Data
    public static class Chunking {

        /**
         * 单个切片的目标最大字符数。
         *
         * <p><b>500 这个值的依据</b>：bge-m3 的单条输入上限是 8192 token，
         * 单看上限可以放很多；但真正决定切片大小的是<b>检索精度</b> ——
         * 切片越长，向量越是把这个区间里所有内容的语义「平均」在一起，
         * 匹配就越糊。中文一个汉字约 0.7~1 个 token，500 字约合 400 个 token，
         * 是「上下文够用」和「语义聚焦」之间的常见折中。
         *
         * <p>⚠️ 这个值<b>不是</b>从哪抄来的标准答案，是本项目的初始假设。
         * 阶段 7 要拿它做 A/B 对比，用真实指标说话。
         */
        private int maxChars = 500;

        /**
         * 相邻切片的重叠字符数。
         *
         * <p>答案横跨切分点时靠它救回来（详见 docs/03 的说明）。
         *
         * <p>取 {@code maxChars} 的 15% 左右是经验上的甜点区：
         * 太小则救不回被切断的句子，太大则相邻切片高度重复，
         * 检索时会把同一个答案返回好几遍，白白占掉 TopK 名额。
         */
        private int overlapChars = 80;

        /**
         * 同类内切出多片时，<b>最后一片</b>低于这个长度就并入前一片。
         *
         * <p>过短的尾片在检索里是纯噪声：一个十几字的片段跟谁的相似度都不低，
         * 容易挤进 TopK 却毫无信息量。
         *
         * <p><b>⚠️ 它的作用范围比名字听起来窄，实测确认过</b>：
         * <ul>
         *   <li>它只处理「一个切分单元内部切出多片」的情况（比如一个 1500 字的章节
         *       切成 3 片，第 3 片只剩 40 字）。</li>
         *   <li>它<b>不</b>会把「两个相邻的小章节」合并 ——
         *       因为那属于跨越章节边界，见 {@code HeadingAwareChunker} 的类不变量。</li>
         * </ul>
         *
         * <p>所以在章节本身就很小的情况下（本项目实测：商品文档按「基本信息 /
         * 卖点 / 适用人群 / 规格参数 &gt; 电池」这样切，单节常在 30~90 字），
         * 这个参数几乎不会被触发，切片就是短的。
         *
         * <p><b>那短切片是不是问题？实测的判断是「不是」</b>：
         * 「规格参数 &gt; 电池 / - 电池容量：5000mAh」这种 40 字的切片，
         * 是一个语义完整、指向明确的检索单元 —— 用户问「电池多大」正好命中它。
         * 强行合并成 500 字反而会把电池、屏幕、摄像头的参数混成一个模糊的向量。
         * 真正该关心的不是「切片够不够长」，而是「一个切片里的内容是不是同一个主题」。
         */
        private int minChars = 80;

        /**
         * 长度保险：一个章节整体短于这个值时不必再切，直接作为一片。
         *
         * <p>实际上就是「如果整个章节都装得下，就别切」——
         * 否则一个 600 字的章节会被切成 500 + 100 两片，
         * 第二片只有 100 字却同样占一个向量，性价比很低。
         */
        private int mergeThresholdChars = 700;

        /** 切分时优先断在这些标点之后，尽量不把句子拦腰截断 */
        private String breakChars = "。！？；!?;\n";

        /**
         * 是否把标题路径拼进切片正文的最前面。默认开。
         *
         * <p><b>为什么默认开</b>：用户问「退货政策是什么」时，「退货」这个词
         * 可能<b>只出现在标题里</b>，正文写的是「签收后 7 天内可申请」。
         * 标题不参与向量化，这个切片就丢了最关键的语义线索。
         * 代价是每个切片重复一次标题路径（约 4% 长度开销）。
         *
         * <p>这个开关是阶段 7 做 A/B 对比的一个现成维度，所以做成可配置的。
         */
        private boolean includeHeadingInContent = true;
    }

    // ================================================================
    // 向量化
    // ================================================================

    @Data
    public static class Embedding {

        /**
         * 单次调用向量化接口的最大条数。
         *
         * <p>32 是和 {@code OpenAiCompatibleEmbeddingClient} 里的常量对齐的
         * （硅基流动对单次 input 数组的长度有限制，太大直接 400）。
         *
         * <p>这里配的是「上层一次提交多少条」，客户端内部还会再按 32 分批，
         * 所以这个值设大一点不会出错，只是内存里会多攒一些待处理的文本。
         * 保持和客户端一致是为了让日志里的批次号看起来直观。
         */
        private int batchSize = 32;

        /**
         * 单条文本送进向量化接口前的字符数上限。
         *
         * <p>正常切分出来的片段不会超过 {@code chunking.maxChars}，
         * 所以这个值是<b>兜底</b>：万一将来有人把 maxChars 调到很大，
         * 或者直接往库里灌一条超长文本，这里会先截断再送，
         * 避免被接口以 400 拒绝而导致整批入库失败。
         *
         * <p>截断会丢失语义，所以发生时会打 WARN 日志 ——
         * 它不该在正常流程里出现。
         */
        private int maxCharsPerText = 4000;
    }

    // ================================================================
    // 入库线程池
    // ================================================================

    /**
     * 异步入库的线程池参数。
     *
     * <p>刻意配得比 {@code sseExecutor} 小得多：向量化是<b>串行调外部 API</b> 的
     * 重活，每个线程都在阻塞等待网络。开太多线程不会让总吞吐变高，
     * 只会同时压更多请求给硅基流动，更快触发限流（429）。
     * 并发度受限于<b>对方的限流阈值</b>，不是我们的 CPU。
     */
    @Data
    public static class Ingest {

        private int corePoolSize = 2;

        private int maxPoolSize = 4;

        /**
         * 队列容量。满了之后按 {@code CallerRunsPolicy} 处理 ——
         * 让提交任务的线程自己跑，从而对上游形成背压。
         *
         * <p>不用 {@code AbortPolicy}（直接抛异常）的原因：入库是用户主动触发的，
         * 抛异常只会变成一句「系统繁忙」，而 CallerRuns 让请求稍微变慢但<b>不丢任务</b>。
         */
        private int queueCapacity = 200;
    }
}
