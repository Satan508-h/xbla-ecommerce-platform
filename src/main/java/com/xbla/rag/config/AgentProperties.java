package com.xbla.rag.config;

import lombok.Data;
import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * 智能体层（阶段 5）配置，对应 {@code application.yml} 里的 {@code xbla.agent}。
 *
 * <p>注册方式：启动类上的 {@code @ConfigurationPropertiesScan} 会自动扫描
 * {@code com.xbla.rag.config} 包下的 {@code @ConfigurationProperties} 类，
 * 不需要写 {@code @EnableConfigurationProperties}。
 *
 * <p><b>目前只有一个字段</b>（意图树文件路径）。后续会往这里加 5.2 的分类
 * 相关旋钮（开关、模型档位）和 5.3 的置信度阈值 ——
 * 那些值同样属于「阶段 7 要做 A/B 对比的旋钮」，按 {@code xbla.rag} 的先例
 * 一律外置成配置，而不是写死在代码里。
 */
@Data
@ConfigurationProperties(prefix = "xbla.agent")
public class AgentProperties {

    /**
     * 分层意图树的定义文件。<b>相对于应用启动目录</b>。
     *
     * <p>放 {@code data/agent/} 而不是 {@code src/main/resources/}，
     * 和 {@code data/corpus/manifest.yml}、{@code data/eval/baseline-questions.yml}
     * 保持一致 —— 这三份都是「人手工维护、程序读取」的声明式数据，
     * 放一起才好找，而且改了不用重新编译打包。
     *
     * <p>⚠️ 但和语料清单有一处刻意的不同：<b>这个文件找不到就直接崩</b>。
     * 语料清单缺少时打 WARN 并回落到 API 的 {@code ?docType=} 参数，
     * 因为那条老路径还在，有合理的兜底；
     * 而意图树没有任何合理的兜底值 —— 「回落」只能等于把所有问题
     * 判成同一类，那是静默地把系统变成坏的系统。
     * 详见 {@code IntentTree} 的类注释。
     */
    private String intentTreePath = "data/agent/intent-tree.yml";

    /** 意图识别（阶段 5.2） */
    private Intent intent = new Intent();

    @Data
    public static class Intent {

        /**
         * 意图识别的总开关。
         *
         * <p>关掉之后 {@code ChatServiceImpl} <b>完全跳过</b>分类与澄清，
         * 走的就是阶段 4 的那条链路（检索 → 生成）。
         *
         * <p><b>默认开</b>，但留这个开关是为了<b>阶段 7 的 A/B</b>：
         * 「意图识别对最终答案质量到底有没有提升」这个问题，
         * 只有拿「开」和「关」两组同样的题跑一遍才能回答。
         * 同 {@code xbla.rag.rewrite.enabled} 的先例。
         *
         * <p>⚠️ 关掉时 {@code qa_log.intent} 存 {@code null}，<b>不是</b>某个默认值 ——
         * 否则阶段 7 分不清「没开意图识别」和「开了但没分出来」，
         * 那是两个完全不同的实验条件。
         */
        private boolean enabled = true;

        /**
         * 澄清反问的话术。
         *
         * <p>固定模板，<b>不调模型生成</b>。理由：澄清路径的全部价值就是
         * <b>短路</b>（不检索、不调大模型），让用户立刻得到反馈；
         * 为了一句反问再调一次模型，会把这条本来最快的路径变得和正常问答一样慢。
         * 而且模板是确定的、可测的。
         *
         * <p>做成配置而不是常量，是因为它属于<b>用户可见的文案</b> ——
         * 那正是最该能改而不重新编译的东西。
         *
         * <p>★ 只问<b>一个</b>问题。罗列「请提供型号、场景、预算……」会让用户
         * 面对一张表单，而澄清的目的是把一次失败的回答变成一次成功的追问。
         */
        private String clarifyText =
                "你是想问哪款商品呢？可以说一下型号，或者你想了解的场景（比如送人、办公、学习），"
                        + "我再帮你看看。";

        /**
         * 意图分类的<b>少样本示例</b>文件。
         *
         * <p>★ 它和 {@code intent-tree.yml} 里的 {@code examples} 字段是两件事，
         * 不能合并：树里的示例是<b>给人看的文档</b>（可以用最典型的问法，
         * 哪怕那句话同时是评测题），这份是<b>给模型看的 prompt 素材</b>
         * （一句都不能是评测题）。合并会导致 5.2 的准确率虚高——
         * 实测两者的交集是 18/20。
         *
         * <p>详见 {@code IntentFewShot} 的类注释。
         */
        private String fewShotPath = "data/agent/intent-fewshot.yml";

        /**
         * 分类请求的 {@code max_tokens}。
         *
         * <p>★★ <b>这个值不能给小。</b> 分类的输出只有几个 token
         * （一个叶子码），直觉上给 16 就够了 —— 但降级链的 P0 是
         * {@code deepseek-flash}，它是<b>推理模型</b>：实测 124 个输出
         * token 里 108 个是推理。给 16 的后果是推理把额度吃光、
         * {@code content} 返回<b>空字符串</b>，表现为「分类永远失败」
         * 而日志里没有任何异常。
         *
         * <p>这是 CLAUDE.md 里记着的那个坑，在 5.2 重新踩一遍的方式。
         * 所以这里默认 {@code null} = 用全局默认的 2048，
         * 真要调小必须先想清楚这件事。
         */
        private Integer maxTokens = null;

        /**
         * 分类请求的 {@code temperature}。
         *
         * <p>默认 {@code 0.0}：不主动往方差里再加东西。
         *
         * <p>⚠️ <b>但 {@code 0.0} 并不能保证确定性</b>（2026-09-19 实测更正）。
         * 同一个问题、同一个模型跑 8 次，出现过 7:1 的结果分裂；
         * 成因是推理模型的浮点并行归约，和阶段 4 记下的
         * 「向量化接口有约 3e-4 漂移」是同一类现象。分类的输出只有几个 token，
         * 几个 token 的差异就直接是另一个答案。
         *
         * <p>【后果】单次测量的准确率有约 ±5% 的逐题波动（n=20 时一道题就是 5%）。
         * 报准确率必须重复多次，见 {@code docs/06}。
         *
         * <p>（真要压住它只能多次采样取多数 —— 而 5.3 正好可以把
         * 「N 次采样的一致度」当置信度用。那是个有代价的设计决定，
         * 由 5.3 拍板，不在这里预设。）
         */
        private Double temperature = 0.0;
    }

    /** 工具调用（阶段 5.8） */
    private Tool tool = new Tool();

    /**
     * 智能体 ⇄ MCP 工具的往返参数。
     *
     * <p>★ 注意它和 {@code xbla.mcp.client} 的分工：
     * <b>这里管「怎么用工具」，那里管「怎么连工具」</b>。
     * 一个是业务策略（最多往返几轮、要不要暴露输出结构），
     * 一个是连接参数（地址、超时）。
     * 混在一起的话，换一个 MCP Server 地址就要把轮次上限也一起搬。
     */
    @Data
    public static class Tool {

        /**
         * 最多允许<b>几轮可以调工具</b>的往返。
         *
         * <p>★★ <b>这个上限不是防模型笨，是防它绕圈。</b>
         * 没有上限时，一个模型完全可以「调工具 → 觉得结果不对 → 再调同一个工具」，
         * 每轮都花一次模型调用和一次数据库查询，而<b>用户那边只是在转圈</b>。
         * 这不是假设：工具返回的结果不理想时，重试是模型的自然反应。
         *
         * <p>默认 3 的依据：
         * <ul>
         *   <li>1 轮覆盖绝大多数问题（调一次工具就回答）</li>
         *   <li>2 轮覆盖「先查订单、看到商品、再查库存」这种链式追问</li>
         *   <li>3 轮是够用的余量。再多基本是模型在试错，
         *       而试错应该由<i>下一次用户提问</i>驱动，不该在一次回答里烧掉</li>
         * </ul>
         *
         * <p>★ <b>它不是模型调用的总次数上限，而是「能带工具的那几轮」的上限。</b>
         * 超过之后还会再走<b>最后一轮</b>，那一轮<b>撤掉工具</b>，强制模型
         * 用手上已有的信息作答。所以总模型调用次数 ≤ {@code maxToolRounds + 1}。
         *
         * <p>⚠️ 为什么要有那个「最后一轮」：不撤工具的话，模型可以在最后一轮
         * 又一次要求调工具，而我们没有轮次可跟了 —— 只能把一个
         * <b>没有正文的 tool_calls 请求</b>当成回答返回给用户（实测
         * {@code content} 是空串），表现为「AI 不说话」。
         *
         * <p>⚠️ 设成 0 表示<b>永远不调工具</b>（但意图树里的 TOOL 类意图仍然
         * 会走这条路，模型会拿到「实时查询不可用」的说明）。它是个给阶段 7
         * 做 A/B 用的开关，不是给人日常配置用的。
         */
        private int maxToolRounds = 3;

        /**
         * 工具往返的 {@code temperature}。
         *
         * <p>★ 默认 {@code 0.0}，和意图分类同一个理由：
         * <b>「调不调工具、调哪个」是个判断，不是创作</b>。
         * 这里要的是稳定复现，不是多样性。
         *
         * <p>⚠️ 同样要知道 {@code 0.0} 不等于确定性
         * （见 {@code AgentProperties.Intent.temperature} 的实测记录）。
         */
        private Double temperature = 0.0;

        /**
         * 实时查询不可用时，塞给模型的<b>那段说明</b>。
         *
         * <p>★ 它存在的理由是 {@code ADR-044}：
         * <b>工具意图退化成裸聊时，模型会凭空编一个订单状态出来。</b>
         * 没有这段话，模型看到用户问「我的订单到哪了」而自己手上什么都没有，
         * 最自然的反应就是「根据一般情况，您的订单预计 3-5 天送达」——
         * 一句听起来完全合理的假话。
         *
         * <p>⚠️ 措辞的关键是<b>给出「不知道」这个选项</b>，而不是只下禁令。
         * 只说「不要编造」时，模型会退而求其次说「系统繁忙，请稍后再试」——
         * 那是另一种不准确（这次不是系统的问题，是没查到）。
         */
        private String unavailableNote =
                "【系统提示】实时查询服务当前不可用。"
                        + "如果用户在问他自己那笔订单、商品的实时库存、或者他账户里的优惠券，"
                        + "请如实告诉用户你现在查不到这些实时数据，并建议他稍后再试。"
                        + "★ 绝对不要根据通用的售后规则去推测某笔具体订单的状态、"
                        + "到货时间或物流信息 —— 那些数据只有实时查询才能拿到。";

        /**
         * 工具列表为空时，工具调用路径的兜底话术（不调模型）。
         *
         * <p>⚠️ 和 {@link #unavailableNote} 是两条不同的路径，别混淆：
         * <ul>
         *   <li>{@code unavailableNote} —— <b>调模型</b>，把情况告诉它，让它组织语言。
         *       用在「工具存在但这次没用上」</li>
         *   <li>本条 —— <b>不调模型</b>，直接回这句。
         *       用在「工具根本没配置」或「用户没有身份」</li>
         * </ul>
         *
         * <p>★ 为什么「没有身份」要不调模型：用户没带 {@code X-Xbla-User-Id}，
         * 我们<b>确实无法</b>查出「他的」订单。这时候让模型发挥，
         * 它唯一的素材就是通用的售后规则 —— 也就是编。
         */
        private String noIdentityText =
                "我需要先知道你是哪位才能查你的订单、库存或者优惠券。"
                        + "请在请求头里带上 X-Xbla-User-Id（本项目还没有登录体系，"
                        + "这一个头就是全部的身份来源）。";
    }
}
